-- =====================================================================================
-- 4. PAYOUT (ERD #29; UC35, UC64; BR-31, BR-45, BR-46, BR-54)
-- The Admin transfers money by hand and records the receipt; no disbursement API (BR-31).
-- =====================================================================================

-- Receiving bank account of a lab or of a consignment seller (UC64: entered by the seller
-- before the payout). One current account per owner; updated after a failed payout (UH-24).
CREATE TABLE payout_accounts (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id             bigint,
    user_account_id         bigint,
    bank_name               varchar(100)   NOT NULL,
    bank_account_number     varchar(30)    NOT NULL,
    account_holder_name     varchar(100)   NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_payout_accounts PRIMARY KEY (id),
    CONSTRAINT ck_payout_accounts_owner CHECK (num_nonnulls(film_lab_id, user_account_id) = 1),
    CONSTRAINT ck_payout_accounts_number CHECK (bank_account_number ~ '^[0-9]{6,30}$'),
    CONSTRAINT ck_payout_accounts_holder CHECK (char_length(account_holder_name) BETWEEN 2 AND 100),
    CONSTRAINT fk_payout_accounts_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_payout_accounts_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);

CREATE UNIQUE INDEX uq_payout_accounts_lab ON payout_accounts (film_lab_id) WHERE film_lab_id IS NOT NULL;
CREATE UNIQUE INDEX uq_payout_accounts_user ON payout_accounts (user_account_id) WHERE user_account_id IS NOT NULL;

COMMENT ON COLUMN payout_accounts.bank_account_number IS 'Personal financial data: shown masked to everyone except the owner and the Admin.';


-- Payout (ERD #29). The bank details are COPIED at execution so that a later change of the
-- payout account does not rewrite where past money went.
CREATE TABLE payouts (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    payout_code             varchar(30)    NOT NULL,
    recipient_type          varchar(20)    NOT NULL,
    film_lab_id             bigint,
    recipient_account_id    bigint,
    amount_vnd              bigint         NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'PENDING',
    bank_name               varchar(100),
    bank_account_number     varchar(30),
    account_holder_name     varchar(100),
    receipt_blob_key        varchar(500),
    executed_by_account_id  bigint,
    paid_at                 timestamptz,
    failure_reason          varchar(500),
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_payouts PRIMARY KEY (id),
    CONSTRAINT uq_payouts_code UNIQUE (payout_code),
    -- FILM_LAB: money of ONLINE orders minus Commission (UC35). SELLER: consignment proceeds (UC64).
    CONSTRAINT ck_payouts_recipient CHECK (
        (recipient_type = 'FILM_LAB' AND film_lab_id IS NOT NULL AND recipient_account_id IS NULL)
        OR (recipient_type = 'SELLER' AND recipient_account_id IS NOT NULL AND film_lab_id IS NULL)),
    CONSTRAINT ck_payouts_amount CHECK (amount_vnd > 0),
    CONSTRAINT ck_payouts_status CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
    -- BR-31: a payout is PAID only with the receipt, the Admin and the bank details used.
    CONSTRAINT ck_payouts_paid CHECK (
        (status = 'PAID') = (paid_at IS NOT NULL)
        AND (status <> 'PAID' OR (receipt_blob_key IS NOT NULL AND executed_by_account_id IS NOT NULL
             AND bank_account_number IS NOT NULL))),
    CONSTRAINT ck_payouts_failed CHECK ((status = 'FAILED') = (failure_reason IS NOT NULL)),
    CONSTRAINT fk_payouts_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_payouts_recipient FOREIGN KEY (recipient_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_payouts_executor FOREIGN KEY (executed_by_account_id) REFERENCES user_accounts (id)
);

-- SCR-58 queue and per-recipient history.
CREATE INDEX ix_payouts_status ON payouts (status, created_at);
CREATE INDEX ix_payouts_lab ON payouts (film_lab_id, created_at DESC) WHERE film_lab_id IS NOT NULL;
CREATE INDEX ix_payouts_seller ON payouts (recipient_account_id, created_at DESC) WHERE recipient_account_id IS NOT NULL;


-- What a payout pays for. One order / one sale is paid out at most once (UC64: the job is
-- idempotent by transaction; a FAILED payout is retried on the same row, not re-created).
-- Eligibility (closed + re-scan window over, BR-46; no open Complaint, BR-45) is checked by
-- the service at creation time.
CREATE TABLE payout_items (
    id                    bigint         GENERATED BY DEFAULT AS IDENTITY,
    payout_id             bigint         NOT NULL,
    service_order_id      bigint,
    consignment_sale_id   bigint,
    amount_vnd            bigint         NOT NULL,
    created_at            timestamptz    NOT NULL DEFAULT now(),
    updated_at            timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_payout_items PRIMARY KEY (id),
    CONSTRAINT ck_payout_items_owner CHECK (num_nonnulls(service_order_id, consignment_sale_id) = 1),
    CONSTRAINT ck_payout_items_amount CHECK (amount_vnd > 0),
    CONSTRAINT fk_payout_items_payout FOREIGN KEY (payout_id) REFERENCES payouts (id) ON DELETE CASCADE,
    CONSTRAINT fk_payout_items_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id)
);

CREATE UNIQUE INDEX uq_payout_items_order ON payout_items (service_order_id) WHERE service_order_id IS NOT NULL;
CREATE UNIQUE INDEX uq_payout_items_sale ON payout_items (consignment_sale_id) WHERE consignment_sale_id IS NOT NULL;
CREATE INDEX ix_payout_items_payout ON payout_items (payout_id);


-- =====================================================================================
-- 5. SUBSCRIPTION PLAN (ERD #16; UC16, UC55 - Tier Simulated UI; BR-28)
-- Minimal: lets the Admin define plans, a lab "buy" one (simulated, no money) and the
-- recommendation show the "display priority" label (BR-28). Not used for ranking.
-- =====================================================================================

CREATE TABLE subscription_plans (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    plan_code               varchar(30)    NOT NULL,
    plan_name               varchar(100)   NOT NULL,
    description             varchar(1000),
    monthly_price_vnd       bigint         NOT NULL,
    has_display_priority    boolean        NOT NULL DEFAULT false,
    status                  varchar(20)    NOT NULL DEFAULT 'ACTIVE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_subscription_plans PRIMARY KEY (id),
    CONSTRAINT uq_subscription_plans_code UNIQUE (plan_code),
    CONSTRAINT ck_subscription_plans_name CHECK (char_length(plan_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_subscription_plans_price CHECK (monthly_price_vnd >= 0),
    CONSTRAINT ck_subscription_plans_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE lab_subscriptions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id             bigint         NOT NULL,
    subscription_plan_id    bigint         NOT NULL,
    starts_at               timestamptz    NOT NULL,
    ends_at                 timestamptz    NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'ACTIVE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_lab_subscriptions PRIMARY KEY (id),
    CONSTRAINT ck_lab_subscriptions_period CHECK (ends_at > starts_at),
    CONSTRAINT ck_lab_subscriptions_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT fk_lab_subscriptions_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_lab_subscriptions_plan FOREIGN KEY (subscription_plan_id) REFERENCES subscription_plans (id)
);

-- One active subscription per lab; also the lookup for the BR-28 label.
CREATE UNIQUE INDEX uq_lab_subscriptions_active ON lab_subscriptions (film_lab_id) WHERE status = 'ACTIVE';


