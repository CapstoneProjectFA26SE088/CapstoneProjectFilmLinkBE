-- =====================================================================================
-- 9. NOTIFICATION (ERD #51; UC04; non-screen #16; UH-37)
-- The row is the in-app notification; each email / push attempt is a delivery row.
-- =====================================================================================

CREATE TABLE notifications (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_account_id         bigint         NOT NULL,
    notification_type       varchar(30)    NOT NULL,
    title                   varchar(150)   NOT NULL,
    content                 varchar(500)   NOT NULL,
    link_path               varchar(500),
    target_type             varchar(30),
    target_id               bigint,
    is_read                 boolean        NOT NULL DEFAULT false,
    read_at                 timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    -- UC04 groups: Processing Stage, payment, debt, moderation, application review, marketplace,
    -- schedule change (UC71), system.
    CONSTRAINT ck_notifications_type CHECK (notification_type IN (
        'ORDER', 'PAYMENT', 'COMMISSION_DEBT', 'MODERATION', 'APPLICATION_REVIEW', 'MARKETPLACE',
        'SCHEDULE_CHANGE', 'COMPLAINT', 'COMMUNITY', 'SYSTEM')),
    CONSTRAINT ck_notifications_read CHECK (is_read = (read_at IS NOT NULL)),
    CONSTRAINT ck_notifications_target CHECK ((target_type IS NULL) = (target_id IS NULL)),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN notifications.link_path IS 'Destination screen inside the app, e.g. /orders/123 (UC04: every notification carries a link).';

-- Notification centre: 20 per page, newest first; unread badge count.
CREATE INDEX ix_notifications_user ON notifications (user_account_id, created_at DESC);
CREATE INDEX ix_notifications_unread ON notifications (user_account_id) WHERE NOT is_read;


CREATE TABLE notification_deliveries (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    notification_id         bigint         NOT NULL,
    channel                 varchar(10)    NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'PENDING',
    attempt_count           smallint       NOT NULL DEFAULT 0,
    next_attempt_at         timestamptz,
    last_error              varchar(1000),
    sent_at                 timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_notification_deliveries PRIMARY KEY (id),
    CONSTRAINT uq_notification_deliveries_channel UNIQUE (notification_id, channel),
    CONSTRAINT ck_notification_deliveries_channel CHECK (channel IN ('EMAIL', 'PUSH')),
    -- SKIPPED: the user turned the channel off, or no FCM token is registered (UC04).
    CONSTRAINT ck_notification_deliveries_status CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    -- UC04: an email is not retried more than 3 times; push uses exponential back-off.
    CONSTRAINT ck_notification_deliveries_attempts CHECK (
        attempt_count >= 0 AND (channel <> 'EMAIL' OR attempt_count <= 3)),
    CONSTRAINT ck_notification_deliveries_sent CHECK ((status = 'SENT') = (sent_at IS NOT NULL)),
    CONSTRAINT fk_notification_deliveries_notification FOREIGN KEY (notification_id)
        REFERENCES notifications (id) ON DELETE CASCADE
);

-- Delivery worker: due attempts.
CREATE INDEX ix_notification_deliveries_due
    ON notification_deliveries (next_attempt_at) WHERE status = 'PENDING';


-- FCM device tokens (UC04 push channel).
CREATE TABLE push_device_tokens (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_account_id         bigint         NOT NULL,
    fcm_token               varchar(500)   NOT NULL,
    platform                varchar(10)    NOT NULL,
    last_registered_at      timestamptz    NOT NULL DEFAULT now(),
    revoked_at              timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_push_device_tokens PRIMARY KEY (id),
    -- A device token belongs to one account at a time (re-login on a shared phone moves it).
    CONSTRAINT uq_push_device_tokens_token UNIQUE (fcm_token),
    CONSTRAINT ck_push_device_tokens_platform CHECK (platform IN ('ANDROID', 'IOS', 'WEB')),
    CONSTRAINT fk_push_device_tokens_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id) ON DELETE CASCADE
);

CREATE INDEX ix_push_device_tokens_user ON push_device_tokens (user_account_id) WHERE revoked_at IS NULL;
