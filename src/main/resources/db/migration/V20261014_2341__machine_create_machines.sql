-- =====================================================================================
-- 1. MACHINE (UC68-UC73, BR-57 - BR-62)
-- =====================================================================================

CREATE TABLE machines (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id         bigint        NOT NULL,
    machine_code        varchar(50)   NOT NULL,
    model_name          varchar(150),
    machine_type        varchar(20)   NOT NULL,
    capacity_per_hour   integer       NOT NULL,
    status              varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_machines PRIMARY KEY (id),
    CONSTRAINT ck_machines_code CHECK (char_length(machine_code) BETWEEN 2 AND 50),
    CONSTRAINT ck_machines_type CHECK (machine_type IN ('PROCESSOR', 'SCANNER')),
    -- PROCESSOR: rolls per hour (default 26). SCANNER: frames per hour (default 327).
    CONSTRAINT ck_machines_capacity CHECK (capacity_per_hour > 0),
    CONSTRAINT ck_machines_status CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'DOWN')),
    CONSTRAINT fk_machines_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id)
);

-- UC68: machine code unique within a lab. Leading film_lab_id also serves "machines of a lab"
-- (UC69 scheduling, UC73 view, lab profile showing SCANNER model_name).
CREATE UNIQUE INDEX uq_machines_lab_code ON machines (film_lab_id, lower(machine_code));

COMMENT ON COLUMN machines.model_name IS 'Shown on the public lab profile for SCANNER machines (replaces the UC12 free-form equipment list).';

-- Many-to-many: processes and formats a machine supports (BR-58 compatibility).
CREATE TABLE machine_film_processes (
    machine_id       bigint  NOT NULL,
    film_process_id  bigint  NOT NULL,
    CONSTRAINT pk_machine_film_processes PRIMARY KEY (machine_id, film_process_id),
    CONSTRAINT fk_mfp_machine FOREIGN KEY (machine_id) REFERENCES machines (id) ON DELETE CASCADE,
    CONSTRAINT fk_mfp_process FOREIGN KEY (film_process_id) REFERENCES film_processes (id)
);

CREATE TABLE machine_film_formats (
    machine_id      bigint  NOT NULL,
    film_format_id  bigint  NOT NULL,
    CONSTRAINT pk_machine_film_formats PRIMARY KEY (machine_id, film_format_id),
    CONSTRAINT fk_mff_machine FOREIGN KEY (machine_id) REFERENCES machines (id) ON DELETE CASCADE,
    CONSTRAINT fk_mff_format FOREIGN KEY (film_format_id) REFERENCES film_formats (id)
);

-- Working hours per machine and day of week (UC68). Scheduling counts only these hours.
CREATE TABLE machine_working_hours (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY,
    machine_id   bigint       NOT NULL,
    day_of_week  smallint     NOT NULL,
    is_closed    boolean      NOT NULL DEFAULT false,
    opens_at     time,
    closes_at    time,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_machine_working_hours PRIMARY KEY (id),
    CONSTRAINT uq_machine_working_hours_day UNIQUE (machine_id, day_of_week),
    CONSTRAINT ck_machine_working_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_machine_working_hours_times CHECK (
        (is_closed AND opens_at IS NULL AND closes_at IS NULL)
        OR (NOT is_closed AND opens_at IS NOT NULL AND closes_at IS NOT NULL AND opens_at < closes_at)),
    CONSTRAINT fk_machine_working_hours_machine FOREIGN KEY (machine_id)
        REFERENCES machines (id) ON DELETE CASCADE
);

-- Machine Incident (ERD #15, UC70).
CREATE TABLE machine_incidents (
    id                      bigint        GENERATED BY DEFAULT AS IDENTITY,
    machine_id              bigint        NOT NULL,
    cause                   varchar(30)   NOT NULL,
    description             varchar(500),
    unavailable_from        timestamptz   NOT NULL,
    expected_available_at   timestamptz,
    machine_status_after    varchar(20)   NOT NULL,
    reported_by_account_id  bigint        NOT NULL,
    resolved_at             timestamptz,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_machine_incidents PRIMARY KEY (id),
    CONSTRAINT ck_machine_incidents_cause CHECK (cause IN
        ('MACHINE_FAILURE', 'CHEMICALS_RUN_OUT', 'CHEMICALS_EXPIRED', 'POWER_OUTAGE', 'OTHER')),
    -- UC70: description required when the cause is OTHER.
    CONSTRAINT ck_machine_incidents_description CHECK (cause <> 'OTHER' OR description IS NOT NULL),
    -- NULL expected_available_at = "undetermined" (then status after must be DOWN).
    CONSTRAINT ck_machine_incidents_period CHECK (
        expected_available_at IS NULL OR expected_available_at > unavailable_from),
    CONSTRAINT ck_machine_incidents_status_after CHECK (
        machine_status_after IN ('MAINTENANCE', 'DOWN')
        AND (expected_available_at IS NOT NULL OR machine_status_after = 'DOWN')),
    CONSTRAINT fk_machine_incidents_machine FOREIGN KEY (machine_id) REFERENCES machines (id),
    CONSTRAINT fk_machine_incidents_reporter FOREIGN KEY (reported_by_account_id) REFERENCES user_accounts (id)
);

-- UC70: up to 5 photos / internal notes for the maintenance record.
CREATE TABLE machine_incident_attachments (
    id                   bigint        GENERATED BY DEFAULT AS IDENTITY,
    machine_incident_id  bigint        NOT NULL,
    file_name            varchar(255)  NOT NULL,
    blob_key             varchar(500)  NOT NULL,
    content_type         varchar(100)  NOT NULL,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_machine_incident_attachments PRIMARY KEY (id),
    CONSTRAINT fk_machine_incident_attachments_incident FOREIGN KEY (machine_incident_id)
        REFERENCES machine_incidents (id) ON DELETE CASCADE
);
