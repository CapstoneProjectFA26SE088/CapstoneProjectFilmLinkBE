-- User Account (ERD #1). Photographer, Photography Expert, Film Lab Owner, Moderator and
-- Admin (ERD #2-#6) are ROLES of this table, not separate tables: none of them has
-- attributes of its own (BR-01: one account, one role).
CREATE TABLE user_accounts (
    id                        bigint        GENERATED BY DEFAULT AS IDENTITY,
    email                     varchar(255)  NOT NULL,
    password_hash             varchar(100)  NOT NULL,
    full_name                 varchar(100)  NOT NULL,
    phone_number              varchar(15),
    avatar_blob_key           varchar(500),
    role                      varchar(30)   NOT NULL,
    status                    varchar(30)   NOT NULL DEFAULT 'PENDING_VERIFICATION',
    lock_reason               varchar(500),
    locked_at                 timestamptz,
    locked_by_account_id      bigint,
    email_verified_at         timestamptz,
    terms_accepted_at         timestamptz,
    failed_login_count        smallint      NOT NULL DEFAULT 0,
    login_locked_until        timestamptz,
    is_in_app_notification_enabled boolean  NOT NULL DEFAULT true,
    is_email_notification_enabled  boolean  NOT NULL DEFAULT true,
    is_push_notification_enabled   boolean  NOT NULL DEFAULT true,
    deleted_at                timestamptz,
    created_at                timestamptz   NOT NULL DEFAULT now(),
    updated_at                timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_user_accounts PRIMARY KEY (id),
    -- UC01 sign-in lookup, UC06 duplicate check. Emails are stored lower-case.
    CONSTRAINT uq_user_accounts_email UNIQUE (email),
    CONSTRAINT ck_user_accounts_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_user_accounts_full_name CHECK (char_length(full_name) BETWEEN 2 AND 100),
    -- [TBC] Photography Expert is a role value switched on the SAME account after approval
    -- (BR-02); role hierarchy in code: PHOTOGRAPHY_EXPERT > PHOTOGRAPHER, ADMIN > MODERATOR.
    CONSTRAINT ck_user_accounts_role CHECK (role IN
        ('PHOTOGRAPHER', 'PHOTOGRAPHY_EXPERT', 'FILM_LAB_OWNER', 'MODERATOR', 'ADMIN')),
    CONSTRAINT ck_user_accounts_status CHECK (status IN
        ('PENDING_VERIFICATION', 'ACTIVE', 'LOCKED', 'DELETED')),
    -- UC11: locking requires a reason (10-500 characters).
    CONSTRAINT ck_user_accounts_lock_reason CHECK (
        status <> 'LOCKED' OR (lock_reason IS NOT NULL AND char_length(lock_reason) >= 10)),
    -- UC06: a self-registered Photographer must have accepted the terms (NFR-PRI-05).
    CONSTRAINT ck_user_accounts_terms CHECK (
        role NOT IN ('PHOTOGRAPHER', 'PHOTOGRAPHY_EXPERT') OR terms_accepted_at IS NOT NULL),
    CONSTRAINT ck_user_accounts_failed_login CHECK (failed_login_count >= 0),
    -- NFR-PRI-05 deletion request: the row is anonymised, not removed (orders, payments
    -- and audit entries still reference it).
    CONSTRAINT ck_user_accounts_deleted CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL)),
    CONSTRAINT fk_user_accounts_locked_by FOREIGN KEY (locked_by_account_id)
        REFERENCES user_accounts (id)
);

-- UC06: job "delete accounts unverified for more than 24 hours".
--   SELECT id FROM user_accounts
--   WHERE status = 'PENDING_VERIFICATION' AND created_at < now() - interval '24 hours';
-- Partial index: only unverified rows are indexed, so it stays tiny.
CREATE INDEX ix_user_accounts_unverified_created
    ON user_accounts (created_at)
    WHERE status = 'PENDING_VERIFICATION';

COMMENT ON TABLE  user_accounts IS 'User Account. Exactly one role per account (BR-01).';
COMMENT ON COLUMN user_accounts.login_locked_until IS 'Temporary sign-in lock after 5 failures in 15 min (UC01, NFR-SEC-07). Not a status.';
COMMENT ON COLUMN user_accounts.lock_reason IS 'Lock applied by the Admin (UC11); shown to the user at sign-in.';


-- Refresh token (not in ERD; required by NFR-SEC-01: 7-day refresh token, revocable).
CREATE TABLE refresh_tokens (
    id                    bigint        GENERATED BY DEFAULT AS IDENTITY,
    user_account_id       bigint        NOT NULL,
    token_hash            char(64)      NOT NULL,
    expires_at            timestamptz   NOT NULL,
    revoked_at            timestamptz,
    replaced_by_token_id  bigint,
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    -- Refresh and sign-out look the token up by its SHA-256 hash; the raw token is never stored.
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT fk_refresh_tokens_account FOREIGN KEY (user_account_id)
        REFERENCES user_accounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_replaced_by FOREIGN KEY (replaced_by_token_id)
        REFERENCES refresh_tokens (id)
);

-- UC02 (password change) and UC11 (account lock) revoke every active token of one account:
--   UPDATE refresh_tokens SET revoked_at = now()
--   WHERE user_account_id = :id AND revoked_at IS NULL;
CREATE INDEX ix_refresh_tokens_active_by_account
    ON refresh_tokens (user_account_id)
    WHERE revoked_at IS NULL;


-- One-time password (not in ERD; UC06 email verification, SCR-03 password reset).
CREATE TABLE otp_codes (
    id                bigint        GENERATED BY DEFAULT AS IDENTITY,
    user_account_id   bigint        NOT NULL,
    purpose           varchar(30)   NOT NULL,
    code_hash         varchar(100)  NOT NULL,
    expires_at        timestamptz   NOT NULL,
    failed_attempts   smallint      NOT NULL DEFAULT 0,
    consumed_at       timestamptz,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_otp_codes PRIMARY KEY (id),
    CONSTRAINT ck_otp_codes_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    -- UC06: maximum 5 incorrect entries.
    CONSTRAINT ck_otp_codes_attempts CHECK (failed_attempts BETWEEN 0 AND 5),
    CONSTRAINT ck_otp_codes_expiry CHECK (expires_at > created_at),
    CONSTRAINT fk_otp_codes_account FOREIGN KEY (user_account_id)
        REFERENCES user_accounts (id) ON DELETE CASCADE
);

-- UC06 runs three queries on every verify / resend:
--   latest code      : ... WHERE user_account_id = :id AND purpose = :p ORDER BY created_at DESC LIMIT 1
--   60-second rule   : same, read created_at of the latest row
--   3 per 15 minutes : SELECT count(*) ... AND created_at > now() - interval '15 minutes'
CREATE INDEX ix_otp_codes_account_purpose_created
    ON otp_codes (user_account_id, purpose, created_at DESC);
