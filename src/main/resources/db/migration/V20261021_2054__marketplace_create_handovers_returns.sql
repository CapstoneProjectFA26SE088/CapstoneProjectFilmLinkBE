-- Consignment Handover (ERD #37, UC63, BR-25 / BR-50): the item leaves the lab, with evidence.
-- Append-only, like film_handovers.
CREATE TABLE consignment_handovers (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_sale_id         bigint         NOT NULL,
    handover_method             varchar(20)    NOT NULL,
    shipment_id                 bigint,
    amount_collected_vnd        bigint,
    is_recipient_code_verified  boolean        NOT NULL DEFAULT false,
    note                        varchar(500),
    performed_by_account_id     bigint         NOT NULL,
    occurred_at                 timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_handovers PRIMARY KEY (id),
    CONSTRAINT uq_consignment_handovers_sale UNIQUE (consignment_sale_id),
    CONSTRAINT ck_consignment_handovers_method CHECK (handover_method IN ('PICKUP_AT_LAB', 'DELIVERY')),
    -- UC63: pickup at the lab is verified with the sale code; delivery goes with a waybill.
    CONSTRAINT ck_consignment_handovers_shape CHECK (
        (handover_method = 'PICKUP_AT_LAB' AND is_recipient_code_verified AND shipment_id IS NULL)
        OR (handover_method = 'DELIVERY' AND shipment_id IS NOT NULL)),
    CONSTRAINT ck_consignment_handovers_amount CHECK (amount_collected_vnd IS NULL OR amount_collected_vnd > 0),
    CONSTRAINT fk_consignment_handovers_sale FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id),
    CONSTRAINT fk_consignment_handovers_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id),
    CONSTRAINT fk_consignment_handovers_performer FOREIGN KEY (performed_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN consignment_handovers.amount_collected_vnd IS 'Pay-at-Lab: must equal consignment_sales.total_vnd (UC63) - checked by the service.';

CREATE TRIGGER consignment_handovers_append_only
    BEFORE UPDATE OR DELETE ON consignment_handovers
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();

-- UC63: 2-10 condition photos at handover.
CREATE TABLE consignment_handover_photos (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_handover_id     bigint         NOT NULL,
    blob_key                    varchar(500)   NOT NULL,
    display_order               smallint       NOT NULL,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_handover_photos PRIMARY KEY (id),
    CONSTRAINT uq_consignment_handover_photos_order UNIQUE (consignment_handover_id, display_order),
    CONSTRAINT ck_consignment_handover_photos_order CHECK (display_order BETWEEN 1 AND 10),
    CONSTRAINT fk_consignment_handover_photos_handover FOREIGN KEY (consignment_handover_id)
        REFERENCES consignment_handovers (id)
);

CREATE TRIGGER consignment_handover_photos_append_only
    BEFORE UPDATE OR DELETE ON consignment_handover_photos
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();


-- Return Request (ERD #38, UC66 - Tier Should, BR-56): within 7 days, when the item differs
-- from its Condition Report. The lab refunds and loses its fee; disagreement -> Admin (BR-47).
CREATE TABLE consignment_return_requests (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_sale_id         bigint         NOT NULL,
    reason                      varchar(2000)  NOT NULL,
    status                      varchar(20)    NOT NULL DEFAULT 'PENDING',
    lab_response_note           varchar(1000),
    responded_at                timestamptz,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_return_requests PRIMARY KEY (id),
    CONSTRAINT uq_consignment_return_requests_sale UNIQUE (consignment_sale_id),
    -- [TBC] UC66 is not specified in detail yet (Review 2); minimum length mirrors UC51.
    CONSTRAINT ck_consignment_return_requests_reason CHECK (char_length(reason) BETWEEN 20 AND 2000),
    -- ESCALATED = the lab disagrees, the Admin decides through a Complaint (UH-49).
    CONSTRAINT ck_consignment_return_requests_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'ESCALATED', 'COMPLETED')),
    CONSTRAINT ck_consignment_return_requests_response CHECK ((status = 'PENDING') = (responded_at IS NULL)),
    CONSTRAINT fk_consignment_return_requests_sale FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id)
);

CREATE TABLE consignment_return_request_photos (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_return_request_id bigint       NOT NULL,
    blob_key                    varchar(500)   NOT NULL,
    display_order               smallint       NOT NULL,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_return_request_photos PRIMARY KEY (id),
    CONSTRAINT uq_consignment_return_request_photos_order UNIQUE (consignment_return_request_id, display_order),
    CONSTRAINT ck_consignment_return_request_photos_order CHECK (display_order BETWEEN 1 AND 10),
    CONSTRAINT fk_crrp_request FOREIGN KEY (consignment_return_request_id)
        REFERENCES consignment_return_requests (id) ON DELETE CASCADE
);


-- Seller Rating (ERD #39, UC67 - Simulated UI): the buyer rates the seller and the inspection.
CREATE TABLE seller_ratings (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_sale_id         bigint         NOT NULL,
    seller_score                smallint       NOT NULL,
    inspection_score            smallint       NOT NULL,
    comment                     varchar(1000),
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_seller_ratings PRIMARY KEY (id),
    CONSTRAINT uq_seller_ratings_sale UNIQUE (consignment_sale_id),
    CONSTRAINT ck_seller_ratings_scores CHECK (seller_score BETWEEN 1 AND 5 AND inspection_score BETWEEN 1 AND 5),
    CONSTRAINT fk_seller_ratings_sale FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id)
);


