-- System Parameter (ERD #52, UC54). Key-value so that adding a parameter is an INSERT,
-- not a schema change. Value validation (ranges, ascending thresholds) lives in the service.
CREATE TABLE system_parameters (
    id                     bigint        GENERATED BY DEFAULT AS IDENTITY,
    param_key              varchar(100)  NOT NULL,
    param_value            varchar(255)  NOT NULL,
    value_type             varchar(20)   NOT NULL,
    description            varchar(500),
    updated_by_account_id  bigint,
    version                integer       NOT NULL DEFAULT 0,
    created_at             timestamptz   NOT NULL DEFAULT now(),
    updated_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_system_parameters PRIMARY KEY (id),
    CONSTRAINT uq_system_parameters_key UNIQUE (param_key),
    CONSTRAINT ck_system_parameters_type CHECK (value_type IN ('INTEGER', 'PERCENT', 'DECIMAL', 'STRING')),
    CONSTRAINT fk_system_parameters_updated_by FOREIGN KEY (updated_by_account_id)
        REFERENCES user_accounts (id)
);

COMMENT ON COLUMN system_parameters.version IS 'Optimistic locking: two Admins saving at once must not overwrite each other silently.';

