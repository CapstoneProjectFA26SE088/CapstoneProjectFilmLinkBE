-- =====================================================================================
-- 6. SALE, HANDOVER, RETURN, RATING (ERD #36-#39; UC62-UC64, UC66, UC67; BR-14, BR-54 - BR-56)
-- =====================================================================================

CREATE TABLE consignment_sales (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    sale_code                   varchar(20)    NOT NULL,
    idempotency_key             uuid           NOT NULL,
    consignment_listing_id      bigint         NOT NULL,
    film_lab_id                 bigint         NOT NULL,
    buyer_account_id            bigint         NOT NULL,
    payment_method              varchar(20)    NOT NULL,
    handover_method             varchar(20)    NOT NULL,
    status                      varchar(25)    NOT NULL DEFAULT 'AWAITING_PAYMENT',
    -- Amounts (UC62): total = item price + shipping fee; no bargaining at this step.
    item_price_vnd              bigint         NOT NULL,
    shipping_fee_vnd            bigint         NOT NULL DEFAULT 0,
    total_vnd                   bigint         NOT NULL,
    -- Delivery address (mandatory for DELIVERY).
    recipient_name              varchar(100),
    recipient_address_line      varchar(255),
    recipient_district          varchar(100),
    recipient_province          varchar(100),
    recipient_phone             varchar(15),
    payment_due_at              timestamptz,
    handed_over_at              timestamptz,
    return_window_ends_at       timestamptz,
    collection_reminder_count   smallint       NOT NULL DEFAULT 0,
    cancelled_at                timestamptz,
    cancellation_reason         varchar(30),
    -- Proceeds split snapshot (UC64, BR-54): fee of the lab, platform commission, seller share.
    consignment_fee_rate        numeric(5,2)   NOT NULL,
    consignment_fee_vnd         bigint         NOT NULL,
    commission_rate             numeric(5,2)   NOT NULL,
    commission_vnd              bigint         NOT NULL,
    seller_payout_vnd           bigint         NOT NULL,
    version                     integer        NOT NULL DEFAULT 0,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_sales PRIMARY KEY (id),
    -- Also the code the buyer shows to collect the item at the lab (UC63).
    CONSTRAINT uq_consignment_sales_code UNIQUE (sale_code),
    CONSTRAINT uq_consignment_sales_idempotency UNIQUE (buyer_account_id, idempotency_key),
    -- BR-14: online through the gateway, or at the lab when collecting. No COD.
    CONSTRAINT ck_consignment_sales_payment CHECK (payment_method IN ('ONLINE', 'PAY_AT_LAB')),
    CONSTRAINT ck_consignment_sales_handover CHECK (handover_method IN ('PICKUP_AT_LAB', 'DELIVERY')),
    -- AWAITING_PAYMENT (online, 15 min) -> AWAITING_HANDOVER -> IN_DELIVERY (DELIVERY only)
    -- -> COMPLETED (in the buyer's hands); CANCELLED; RETURNED (UC66 accepted).
    CONSTRAINT ck_consignment_sales_status CHECK (status IN (
        'AWAITING_PAYMENT', 'AWAITING_HANDOVER', 'IN_DELIVERY', 'COMPLETED', 'CANCELLED', 'RETURNED')),
    CONSTRAINT ck_consignment_sales_amounts CHECK (
        item_price_vnd > 0 AND shipping_fee_vnd >= 0 AND total_vnd = item_price_vnd + shipping_fee_vnd),
    CONSTRAINT ck_consignment_sales_shipping CHECK (handover_method = 'DELIVERY' OR shipping_fee_vnd = 0),
    CONSTRAINT ck_consignment_sales_address CHECK (
        handover_method <> 'DELIVERY'
        OR (recipient_name IS NOT NULL AND recipient_address_line IS NOT NULL AND recipient_district IS NOT NULL
            AND recipient_province IS NOT NULL AND recipient_phone IS NOT NULL)),
    CONSTRAINT ck_consignment_sales_online_due CHECK ((payment_method = 'ONLINE') = (payment_due_at IS NOT NULL)),
    CONSTRAINT ck_consignment_sales_handed CHECK (
        (status IN ('COMPLETED', 'RETURNED')) <= (handed_over_at IS NOT NULL)),
    -- BR-56: return requested within 7 days of receiving the item.
    CONSTRAINT ck_consignment_sales_return_window CHECK ((handed_over_at IS NULL) = (return_window_ends_at IS NULL)),
    -- UH-47: reminders on day 7 and day 12.
    CONSTRAINT ck_consignment_sales_reminders CHECK (collection_reminder_count BETWEEN 0 AND 2),
    CONSTRAINT ck_consignment_sales_cancel CHECK (
        (status = 'CANCELLED') = (cancelled_at IS NOT NULL)
        AND (cancelled_at IS NULL) = (cancellation_reason IS NULL)
        AND (cancellation_reason IS NULL OR cancellation_reason IN (
            'PAYMENT_EXPIRED', 'BUYER_ABANDONED', 'ITEM_LOST_OR_DAMAGED', 'SOLD_TO_ANOTHER_BUYER', 'ADMIN_DECISION'))),
    -- BR-54: seller share = price - lab fee - commission (all on the item price, not the shipping fee).
    CONSTRAINT ck_consignment_sales_split CHECK (
        consignment_fee_rate BETWEEN 0 AND 100 AND commission_rate BETWEEN 0 AND 100
        AND consignment_fee_vnd >= 0 AND commission_vnd >= 0 AND seller_payout_vnd >= 0
        AND seller_payout_vnd = item_price_vnd - consignment_fee_vnd - commission_vnd),
    CONSTRAINT fk_consignment_sales_listing FOREIGN KEY (consignment_listing_id) REFERENCES consignment_listings (id),
    CONSTRAINT fk_consignment_sales_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_consignment_sales_buyer FOREIGN KEY (buyer_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN consignment_sales.cancellation_reason IS 'BUYER_ABANDONED is the "abandoned purchase recorded against the buyer" of UC63; counted per query.';

-- UH-46: at most one live sale per listing; a cancelled one frees the listing.
CREATE UNIQUE INDEX uq_consignment_sales_live
    ON consignment_sales (consignment_listing_id) WHERE status <> 'CANCELLED';

-- Buyer's purchases, newest first.
CREATE INDEX ix_consignment_sales_buyer ON consignment_sales (buyer_account_id, created_at DESC);

-- Lab handover queue (UC63) and the 14-day uncollected job (non-screen #28).
CREATE INDEX ix_consignment_sales_lab_status ON consignment_sales (film_lab_id, status, created_at);

-- Online purchases whose 15-minute link expired (listing unlocked again).
CREATE INDEX ix_consignment_sales_awaiting_payment
    ON consignment_sales (payment_due_at) WHERE status = 'AWAITING_PAYMENT';


-- Link the money tables of cluster 3 to the sale.
ALTER TABLE payments ADD CONSTRAINT fk_payments_sale
    FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id);
ALTER TABLE commissions ADD CONSTRAINT fk_commissions_sale
    FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id);
ALTER TABLE payout_items ADD CONSTRAINT fk_payout_items_sale
    FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id);
