-- Development Batch (ERD #19): rolls with the same process and format on one PROCESSOR.
CREATE TABLE development_batches (
    id                    bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id           bigint        NOT NULL,
    machine_id            bigint        NOT NULL,
    film_process_id       bigint        NOT NULL,
    film_format_id        bigint        NOT NULL,
    scheduled_start_at    timestamptz   NOT NULL,
    scheduled_end_at      timestamptz   NOT NULL,
    status                varchar(20)   NOT NULL DEFAULT 'PROPOSED',
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_development_batches PRIMARY KEY (id),
    CONSTRAINT ck_development_batches_time CHECK (scheduled_end_at > scheduled_start_at),
    CONSTRAINT ck_development_batches_status CHECK (status IN
        ('PROPOSED', 'CONFIRMED', 'RUNNING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_development_batches_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_development_batches_machine FOREIGN KEY (machine_id) REFERENCES machines (id),
    CONSTRAINT fk_development_batches_process FOREIGN KEY (film_process_id) REFERENCES film_processes (id),
    CONSTRAINT fk_development_batches_format FOREIGN KEY (film_format_id) REFERENCES film_formats (id)
);

ALTER TABLE film_rolls ADD CONSTRAINT fk_film_rolls_batch
    FOREIGN KEY (development_batch_id) REFERENCES development_batches (id);

-- UC69 / UC70 / UC73: timeline of one machine in a period (free slot, incident impact):
--   WHERE machine_id = :m AND scheduled_start_at < :to AND scheduled_end_at > :from
CREATE INDEX ix_development_batches_machine_time
    ON development_batches (machine_id, scheduled_start_at);

-- Scan Job (ERD #20): one roll on one SCANNER, queued; a re-scan creates a new job (BR-27).
CREATE TABLE scan_jobs (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_roll_id        bigint        NOT NULL,
    machine_id          bigint        NOT NULL,
    frame_count         smallint      NOT NULL,
    scheduled_start_at  timestamptz   NOT NULL,
    scheduled_end_at    timestamptz   NOT NULL,
    status              varchar(20)   NOT NULL DEFAULT 'QUEUED',
    rescan_request_id   bigint,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_scan_jobs PRIMARY KEY (id),
    CONSTRAINT ck_scan_jobs_frames CHECK (frame_count BETWEEN 1 AND 100),
    CONSTRAINT ck_scan_jobs_time CHECK (scheduled_end_at > scheduled_start_at),
    CONSTRAINT ck_scan_jobs_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_scan_jobs_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id),
    CONSTRAINT fk_scan_jobs_machine FOREIGN KEY (machine_id) REFERENCES machines (id)
);

-- BR-60 "waiting time in the scan queue": open jobs of one scanner in time order.
CREATE INDEX ix_scan_jobs_machine_queue
    ON scan_jobs (machine_id, scheduled_start_at)
    WHERE status IN ('QUEUED', 'RUNNING');

-- Schedule change caused by an incident (UC71) and the customer's answer (UC72).
-- Also the trail required by CR-20 (old/new promised date, step applied).
CREATE TABLE schedule_changes (
    id                    bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id      bigint        NOT NULL,
    machine_incident_id   bigint        NOT NULL,
    step_applied          varchar(20)   NOT NULL,
    old_promised_at       timestamptz   NOT NULL,
    new_promised_at       timestamptz   NOT NULL,
    requires_response     boolean       NOT NULL,
    response_due_at       timestamptz,
    customer_choice       varchar(20),
    customer_note         varchar(300),
    responded_at          timestamptz,
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_schedule_changes PRIMARY KEY (id),
    -- BR-62: (a) moved to another machine, (b) queue pushed back; (c) is requires_response = true.
    CONSTRAINT ck_schedule_changes_step CHECK (step_applied IN ('MOVED_MACHINE', 'RESCHEDULED')),
    CONSTRAINT ck_schedule_changes_response CHECK (
        requires_response = (response_due_at IS NOT NULL)
        AND (customer_choice IS NULL OR requires_response)),
    -- UC72: wait / cancel with full refund / transfer to another lab; default after 48 h is WAIT (UH-53).
    CONSTRAINT ck_schedule_changes_choice CHECK (customer_choice IS NULL OR customer_choice IN ('WAIT', 'CANCEL', 'TRANSFER')),
    CONSTRAINT ck_schedule_changes_answered CHECK ((customer_choice IS NULL) = (responded_at IS NULL)),
    CONSTRAINT fk_schedule_changes_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_schedule_changes_incident FOREIGN KEY (machine_incident_id) REFERENCES machine_incidents (id)
);

-- Order detail shows its schedule changes.
CREATE INDEX ix_schedule_changes_order ON schedule_changes (service_order_id);

-- UH-53 job: answers not received in time are deemed WAIT.
--   WHERE requires_response AND customer_choice IS NULL AND response_due_at < now()
CREATE INDEX ix_schedule_changes_awaiting_response
    ON schedule_changes (response_due_at)
    WHERE requires_response AND customer_choice IS NULL;
