-- Commission Debt (ERD #28): what one lab owes for one Billing Period (calendar month).
CREATE TABLE commission_debts (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id             bigint         NOT NULL,
    billing_period          date           NOT NULL,
    due_date                date           NOT NULL,
    total_amount_vnd        bigint         NOT NULL,
    paid_amount_vnd         bigint         NOT NULL DEFAULT 0,
    status                  varchar(20)    NOT NULL DEFAULT 'UNPAID',
    settled_at              timestamptz,
    settled_by_account_id   bigint,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_commission_debts PRIMARY KEY (id),
    -- UC32: re-running the closing job never creates a second debt (idempotent by lab + period).
    CONSTRAINT uq_commission_debts_lab_period UNIQUE (film_lab_id, billing_period),
    -- billing_period is the first day of the month (2026-10-01 = period "2026-10").
    CONSTRAINT ck_commission_debts_period CHECK (extract(day FROM billing_period) = 1),
    -- BR-20: due on day BILLING_DUE_DAY_OF_MONTH of the following month.
    CONSTRAINT ck_commission_debts_due CHECK (due_date > billing_period + interval '1 month' - interval '1 day'),
    CONSTRAINT ck_commission_debts_amounts CHECK (
        total_amount_vnd > 0 AND paid_amount_vnd BETWEEN 0 AND total_amount_vnd),
    -- UC34: a partial payment does not lift sanctions; only PAID does.
    CONSTRAINT ck_commission_debts_status CHECK (status IN ('UNPAID', 'PARTIALLY_PAID', 'PAID')),
    CONSTRAINT ck_commission_debts_paid CHECK (
        (status = 'PAID') = (paid_amount_vnd = total_amount_vnd)
        AND (status = 'PAID') = (settled_at IS NOT NULL)
        AND (status <> 'UNPAID' OR paid_amount_vnd = 0)),
    CONSTRAINT fk_commission_debts_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_commission_debts_settled_by FOREIGN KEY (settled_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN commission_debts.total_amount_vnd IS 'Sum of the BILLED commissions (adjustments included). If the net sum of a period is <= 0, no debt is created and the rows stay OPEN for the next period (UC32 "no debt record").';
COMMENT ON COLUMN commission_debts.settled_by_account_id IS 'Admin who confirmed the last payment (UC33); sanctions are lifted at that moment (BR-21).';

-- UC34 (daily 03:00) and UC33 "oldest period first": open debts of a lab by age.
CREATE INDEX ix_commission_debts_open
    ON commission_debts (film_lab_id, billing_period) WHERE status <> 'PAID';

ALTER TABLE payments ADD CONSTRAINT fk_payments_debt
    FOREIGN KEY (commission_debt_id) REFERENCES commission_debts (id);


-- Commission (ERD #27): the platform fee of one closed Service Order or one consignment sale,
-- plus ADJUSTMENT rows that correct a Billing Period already closed (UC52, UC64: "deduction in
-- the next Billing Period instead of amending the closed one").
CREATE TABLE commissions (
    id                    bigint         GENERATED BY DEFAULT AS IDENTITY,
    kind                  varchar(20)    NOT NULL,
    film_lab_id           bigint         NOT NULL,
    service_order_id      bigint,
    consignment_sale_id   bigint,
    complaint_id          bigint,
    base_amount_vnd       bigint         NOT NULL,
    rate_percent          numeric(5,2)   NOT NULL,
    amount_vnd            bigint         NOT NULL,
    collection_mode       varchar(20)    NOT NULL,
    status                varchar(20)    NOT NULL DEFAULT 'OPEN',
    commission_debt_id    bigint,
    eligible_at           timestamptz    NOT NULL,
    waiver_reason         varchar(500),
    created_at            timestamptz    NOT NULL DEFAULT now(),
    updated_at            timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_commissions PRIMARY KEY (id),
    CONSTRAINT ck_commissions_kind CHECK (kind IN ('ORDER', 'SALE', 'ADJUSTMENT')),
    CONSTRAINT ck_commissions_owner CHECK (
        num_nonnulls(service_order_id, consignment_sale_id) = 1
        AND (kind <> 'ORDER' OR service_order_id IS NOT NULL)
        AND (kind <> 'SALE' OR consignment_sale_id IS NOT NULL)),
    -- An adjustment always comes from a decided Complaint.
    CONSTRAINT ck_commissions_adjustment CHECK ((kind = 'ADJUSTMENT') = (complaint_id IS NOT NULL)),
    CONSTRAINT ck_commissions_rate CHECK (rate_percent BETWEEN 0 AND 100),
    -- Only an adjustment can be negative (it reduces the next period). BR-26 damaged rolls are
    -- already excluded from base_amount_vnd; a waived commission has amount 0 and a reason.
    CONSTRAINT ck_commissions_amounts CHECK (
        base_amount_vnd >= 0 AND (kind = 'ADJUSTMENT' OR amount_vnd >= 0)),
    CONSTRAINT ck_commissions_waiver CHECK (waiver_reason IS NULL OR amount_vnd = 0),
    -- DEDUCTED = money passed through the platform (ONLINE): kept at source, never a debt.
    -- DEBT = PAY_AT_LAB / COD order or Pay-at-Lab sale: goes into the lab's Commission Debt (BR-10, BR-55).
    CONSTRAINT ck_commissions_mode CHECK (collection_mode IN ('DEDUCTED', 'DEBT')),
    -- OPEN = waiting for the period closing; DEFERRED = open Complaint at closing, moved to the next
    -- period (UC32); BILLED = inside a debt; SETTLED = DEDUCTED at source.
    CONSTRAINT ck_commissions_status CHECK (status IN ('OPEN', 'DEFERRED', 'BILLED', 'SETTLED')),
    CONSTRAINT ck_commissions_billing CHECK (
        (status = 'BILLED') = (commission_debt_id IS NOT NULL)
        AND (collection_mode = 'DEBT' OR status = 'SETTLED')),
    CONSTRAINT fk_commissions_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_commissions_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_commissions_debt FOREIGN KEY (commission_debt_id) REFERENCES commission_debts (id)
);

COMMENT ON COLUMN commissions.rate_percent IS 'Rate actually applied, copied from the rule/parameter at calculation time.';
COMMENT ON COLUMN commissions.eligible_at IS 'Order closed (UC32) or sale settled (UC64): decides the Billing Period.';
COMMENT ON COLUMN commissions.complaint_id IS 'FK to complaints is added in cluster 5.';

-- One regular commission per order and per sale; adjustments are extra rows.
CREATE UNIQUE INDEX uq_commissions_order ON commissions (service_order_id) WHERE kind = 'ORDER';
CREATE UNIQUE INDEX uq_commissions_sale ON commissions (consignment_sale_id) WHERE kind = 'SALE';

-- UC32 closing job: open DEBT commissions of one lab up to the end of the period.
CREATE INDEX ix_commissions_unbilled
    ON commissions (film_lab_id, eligible_at) WHERE status IN ('OPEN', 'DEFERRED');

-- Debt statement (SCR-45): lines of one debt.
CREATE INDEX ix_commissions_debt ON commissions (commission_debt_id) WHERE commission_debt_id IS NOT NULL;


-- Debt reminders (BR-22): automatic on day 1, 5, 8; manual contacts by the Admin from day 11,
-- with the outcome recorded "in the debt file".
CREATE TABLE commission_debt_reminders (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    commission_debt_id      bigint         NOT NULL,
    reminder_type           varchar(10)    NOT NULL,
    reminder_day            smallint,
    contacted_by_account_id bigint,
    contact_outcome         varchar(1000),
    reminded_at             timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_commission_debt_reminders PRIMARY KEY (id),
    CONSTRAINT ck_commission_debt_reminders_type CHECK (reminder_type IN ('AUTO', 'MANUAL')),
    CONSTRAINT ck_commission_debt_reminders_shape CHECK (
        (reminder_type = 'AUTO' AND reminder_day IN (1, 5, 8) AND contacted_by_account_id IS NULL)
        OR (reminder_type = 'MANUAL' AND reminder_day IS NULL
            AND contacted_by_account_id IS NOT NULL AND contact_outcome IS NOT NULL)),
    -- Non-screen #7: an automatic reminder is sent once per debt and day, even if the job re-runs.
    CONSTRAINT uq_commission_debt_reminders_auto UNIQUE (commission_debt_id, reminder_day),
    CONSTRAINT fk_commission_debt_reminders_debt FOREIGN KEY (commission_debt_id) REFERENCES commission_debts (id),
    CONSTRAINT fk_commission_debt_reminders_admin FOREIGN KEY (contacted_by_account_id) REFERENCES user_accounts (id)
);

CREATE TRIGGER commission_debt_reminders_append_only
    BEFORE UPDATE OR DELETE ON commission_debt_reminders
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();


-- Sanction (ERD #30, UC34, BR-21): history of the sanction level of a lab.
-- The level a query must apply is the row with lifted_at IS NULL (at most one per lab).
-- Keeping history lets the job notify only on a level CHANGE and gives the Admin the trail.
CREATE TABLE lab_sanctions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id             bigint         NOT NULL,
    commission_debt_id      bigint         NOT NULL,
    sanction_level          smallint       NOT NULL,
    applied_at              timestamptz    NOT NULL DEFAULT now(),
    lifted_at               timestamptz,
    lift_reason             varchar(20),
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_lab_sanctions PRIMARY KEY (id),
    -- 1 = excluded from Lab Recommendation, 2 = hidden from search, 3 = no new orders (BR-21).
    CONSTRAINT ck_lab_sanctions_level CHECK (sanction_level BETWEEN 1 AND 3),
    -- ESCALATED = replaced by a higher level; DEBT_PAID = Admin confirmed payment (UC33).
    CONSTRAINT ck_lab_sanctions_lift CHECK (
        (lifted_at IS NULL) = (lift_reason IS NULL)
        AND (lift_reason IS NULL OR lift_reason IN ('ESCALATED', 'DEBT_PAID'))),
    CONSTRAINT fk_lab_sanctions_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    -- The longest overdue period at application time (UC34: level follows the oldest debt).
    CONSTRAINT fk_lab_sanctions_debt FOREIGN KEY (commission_debt_id) REFERENCES commission_debts (id)
);

-- One active level per lab; also the lookup used by search (UC17) and recommendation (UC18).
CREATE UNIQUE INDEX uq_lab_sanctions_active ON lab_sanctions (film_lab_id) WHERE lifted_at IS NULL;
