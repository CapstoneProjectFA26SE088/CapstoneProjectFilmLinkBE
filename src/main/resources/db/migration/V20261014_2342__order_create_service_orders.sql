-- Service Order (ERD #17). Never physically deleted: cancelling is a status (CR-15).
CREATE TABLE service_orders (
    id                              bigint        GENERATED BY DEFAULT AS IDENTITY,
    order_code                      varchar(20)   NOT NULL,
    idempotency_key                 uuid          NOT NULL,
    photographer_account_id         bigint        NOT NULL,
    film_lab_id                     bigint        NOT NULL,
    status                          varchar(40)   NOT NULL DEFAULT 'AWAITING_PAYMENT',
    status_before_suspension        varchar(40),
    service_tier                    varchar(20)   NOT NULL,
    film_handover_method            varchar(20)   NOT NULL,
    payment_method                  varchar(20)   NOT NULL,
    special_request                 varchar(500),
    -- Customer address: pickup point (PICKUP / PARCEL_SHIPPING) and default return address (UC27).
    customer_address_line           varchar(255),
    customer_district               varchar(100),
    customer_province               varchar(100),
    customer_phone                  varchar(15),
    pickup_window_start_at          timestamptz,
    pickup_window_end_at            timestamptz,
    -- Price snapshot (UC20 provisional, UC23 final). Amounts paid / refunded live in payments (cluster 3).
    estimated_total_vnd             bigint        NOT NULL,
    final_total_vnd                 bigint,
    price_locked_at                 timestamptz,
    -- Dates (BR-60: expected at creation, promised after machine assignment).
    expected_return_at              timestamptz   NOT NULL,
    promised_return_at              timestamptz,
    machine_assignment_confirmed_at timestamptz,
    lab_response_due_at             timestamptz,
    accepted_at                     timestamptz,
    rejection_reason                varchar(500),
    delivered_at                    timestamptz,
    closed_at                       timestamptz,
    keep_negatives_at_lab           boolean       NOT NULL DEFAULT false,
    cancelled_at                    timestamptz,
    cancelled_by_account_id         bigint,
    cancellation_reason             varchar(500),
    cancellation_fee_vnd            bigint,
    version                         integer       NOT NULL DEFAULT 0,
    created_at                      timestamptz   NOT NULL DEFAULT now(),
    updated_at                      timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_service_orders PRIMARY KEY (id),
    -- MSG18 {order_code}.
    CONSTRAINT uq_service_orders_code UNIQUE (order_code),
    -- NFR-REL-02: re-sending the same create request must not create a second order.
    CONSTRAINT uq_service_orders_idempotency UNIQUE (photographer_account_id, idempotency_key),
    -- [TBC] State model 14/10/2026. Processing Stages (BR-07) are a separate table.
    CONSTRAINT ck_service_orders_status CHECK (status IN (
        'AWAITING_PAYMENT', 'AWAITING_LAB_CONFIRMATION', 'AWAITING_FILM',
        'AWAITING_MACHINE_ASSIGNMENT', 'IN_PROCESSING', 'AWAITING_TOP_UP',
        'READY_FOR_HANDOVER', 'DELIVERED', 'CLOSED', 'CANCELLED', 'SUSPENDED')),
    CONSTRAINT ck_service_orders_suspension CHECK ((status = 'SUSPENDED') = (status_before_suspension IS NOT NULL)),
    CONSTRAINT ck_service_orders_tier CHECK (service_tier IN ('STANDARD', 'EXPRESS')),
    CONSTRAINT ck_service_orders_handover CHECK (film_handover_method IN ('SELF_DROP_OFF', 'PICKUP', 'PARCEL_SHIPPING')),
    CONSTRAINT ck_service_orders_payment_method CHECK (payment_method IN ('ONLINE', 'PAY_AT_LAB', 'COD')),
    -- BR-09: COD only with PICKUP or PARCEL_SHIPPING.
    CONSTRAINT ck_service_orders_cod CHECK (payment_method <> 'COD' OR film_handover_method <> 'SELF_DROP_OFF'),
    -- UC20: address and time window mandatory unless Self Drop-off.
    CONSTRAINT ck_service_orders_customer_address CHECK (
        film_handover_method = 'SELF_DROP_OFF'
        OR (customer_address_line IS NOT NULL AND customer_district IS NOT NULL
            AND customer_province IS NOT NULL AND customer_phone IS NOT NULL
            AND pickup_window_start_at IS NOT NULL AND pickup_window_end_at IS NOT NULL)),
    CONSTRAINT ck_service_orders_pickup_window CHECK (
        pickup_window_start_at IS NULL OR pickup_window_end_at > pickup_window_start_at),
    CONSTRAINT ck_service_orders_amounts CHECK (
        estimated_total_vnd >= 0 AND (final_total_vnd IS NULL OR final_total_vnd >= 0)
        AND (cancellation_fee_vnd IS NULL OR cancellation_fee_vnd >= 0)),
    CONSTRAINT ck_service_orders_price_lock CHECK ((final_total_vnd IS NULL) = (price_locked_at IS NULL)),
    CONSTRAINT ck_service_orders_promised CHECK (
        (promised_return_at IS NULL) = (machine_assignment_confirmed_at IS NULL)),
    CONSTRAINT ck_service_orders_cancel CHECK (
        (status = 'CANCELLED') = (cancelled_at IS NOT NULL)
        AND (cancelled_at IS NULL OR cancellation_reason IS NOT NULL)),
    CONSTRAINT ck_service_orders_rejection CHECK (rejection_reason IS NULL OR char_length(rejection_reason) >= 10),
    CONSTRAINT fk_service_orders_photographer FOREIGN KEY (photographer_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_service_orders_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_service_orders_cancelled_by FOREIGN KEY (cancelled_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN service_orders.lab_response_due_at IS 'Snapshot of now() + LAB_RESPONSE_LIMIT_HOURS when the order reaches the lab; a later parameter change does not move it.';
COMMENT ON COLUMN service_orders.version IS 'Optimistic locking: the lab accepting and the Photographer cancelling at the same moment.';

-- SCR-18 "My Service Orders", newest first, optionally filtered by status:
--   WHERE photographer_account_id = :me [AND status = :s] ORDER BY created_at DESC
CREATE INDEX ix_service_orders_photographer_created
    ON service_orders (photographer_account_id, created_at DESC);

-- SCR-42 / SCR-43 lab order queue: WHERE film_lab_id = :lab AND status = :s ORDER BY created_at
CREATE INDEX ix_service_orders_lab_status_created
    ON service_orders (film_lab_id, status, created_at);

-- Scheduled jobs select by status and age: unpaid > 24 h (UH-18), lab no response (UC22),
-- Self Drop-off not brought in (BR-23), auto-close DELIVERED after 7 days (BR-24 / UC29).
CREATE INDEX ix_service_orders_status_created
    ON service_orders (status, created_at);


-- Film Roll (ERD #18). The unit of scheduling and of the archive.
CREATE TABLE film_rolls (
    id                              bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id                bigint        NOT NULL,
    roll_sequence                   smallint      NOT NULL,
    film_stock_id                   bigint,
    film_stock_name_text            varchar(100),
    film_format_id                  bigint        NOT NULL,
    film_process_id                 bigint        NOT NULL,
    service_package_id              bigint        NOT NULL,
    service_package_scan_option_id  bigint,
    exposure_count                  smallint      NOT NULL,
    shooting_iso                    smallint,
    push_pull_stops                 smallint      NOT NULL DEFAULT 0,
    -- Price snapshot at order creation (UC13: later price changes do not affect the order).
    unit_price_vnd                  bigint        NOT NULL,
    scan_option_price_vnd           bigint        NOT NULL DEFAULT 0,
    push_pull_surcharge_vnd         bigint        NOT NULL DEFAULT 0,
    express_surcharge_vnd           bigint        NOT NULL DEFAULT 0,
    status                          varchar(20)   NOT NULL DEFAULT 'DECLARED',
    is_added_at_receipt             boolean       NOT NULL DEFAULT false,
    damage_note                     varchar(500),
    development_batch_id            bigint,
    created_at                      timestamptz   NOT NULL DEFAULT now(),
    updated_at                      timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_film_rolls PRIMARY KEY (id),
    -- UC20: 1-20 declared rolls; UC23 may add up to 5 more at receipt.
    CONSTRAINT uq_film_rolls_sequence UNIQUE (service_order_id, roll_sequence),
    CONSTRAINT ck_film_rolls_sequence CHECK (roll_sequence BETWEEN 1 AND 25),
    -- UC20: stock selected from the catalogue OR typed freely - exactly one of the two.
    CONSTRAINT ck_film_rolls_stock CHECK ((film_stock_id IS NULL) <> (film_stock_name_text IS NULL)),
    CONSTRAINT ck_film_rolls_exposures CHECK (exposure_count BETWEEN 1 AND 40),
    CONSTRAINT ck_film_rolls_iso CHECK (shooting_iso IS NULL OR shooting_iso BETWEEN 1 AND 12800),
    CONSTRAINT ck_film_rolls_push_pull CHECK (push_pull_stops BETWEEN -3 AND 3),
    CONSTRAINT ck_film_rolls_prices CHECK (
        unit_price_vnd > 0 AND scan_option_price_vnd >= 0
        AND push_pull_surcharge_vnd >= 0 AND express_surcharge_vnd >= 0),
    -- DECLARED by the customer -> RECEIVED / NOT_RECEIVED when counted (UC23) -> DAMAGED (BR-26, free of charge).
    CONSTRAINT ck_film_rolls_status CHECK (status IN ('DECLARED', 'RECEIVED', 'NOT_RECEIVED', 'DAMAGED')),
    CONSTRAINT ck_film_rolls_damage CHECK ((status = 'DAMAGED') = (damage_note IS NOT NULL)),
    CONSTRAINT fk_film_rolls_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_film_rolls_stock FOREIGN KEY (film_stock_id) REFERENCES film_stocks (id),
    CONSTRAINT fk_film_rolls_format FOREIGN KEY (film_format_id) REFERENCES film_formats (id),
    CONSTRAINT fk_film_rolls_process FOREIGN KEY (film_process_id) REFERENCES film_processes (id),
    CONSTRAINT fk_film_rolls_package FOREIGN KEY (service_package_id) REFERENCES service_packages (id),
    CONSTRAINT fk_film_rolls_scan_option FOREIGN KEY (service_package_scan_option_id)
        REFERENCES service_package_scan_options (id)
);

COMMENT ON COLUMN film_rolls.film_process_id IS 'Copied from the chosen Service Package; kept on the roll because scheduling (BR-58, BR-59) groups rolls by it.';
COMMENT ON COLUMN film_rolls.service_package_scan_option_id IS '[TBC] UC20 does not yet say whether the scan resolution is chosen per roll.';

-- UC69 / UC70: rolls of one developing batch (impact of an incident, batch detail).
CREATE INDEX ix_film_rolls_batch
    ON film_rolls (development_batch_id)
    WHERE development_batch_id IS NOT NULL;

-- UC24: evidence photos of a damaged roll (BR-26).
CREATE TABLE film_roll_damage_photos (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_roll_id  bigint        NOT NULL,
    blob_key      varchar(500)  NOT NULL,
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_roll_damage_photos PRIMARY KEY (id),
    CONSTRAINT fk_film_roll_damage_photos_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id)
);


-- Processing Stage Record (ERD #21, UC24, BR-07). Append-only history; the current stage
-- of an order is its latest record (not stored twice).
CREATE TABLE processing_stage_records (
    id                      bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id        bigint        NOT NULL,
    stage                   varchar(20)   NOT NULL,
    note                    varchar(300),
    is_admin_reversion      boolean       NOT NULL DEFAULT false,
    recorded_by_account_id  bigint        NOT NULL,
    recorded_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_processing_stage_records PRIMARY KEY (id),
    CONSTRAINT ck_processing_stage_records_stage CHECK (stage IN
        ('RECEIVED', 'DEVELOPING', 'WASHING', 'DRYING', 'SCANNING', 'QC')),
    CONSTRAINT fk_processing_stage_records_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_processing_stage_records_actor FOREIGN KEY (recorded_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN processing_stage_records.is_admin_reversion IS 'UC24: only the Admin can move a stage back; it is a new record, never an update.';

-- SCR-19 timeline and "current stage" lookup: WHERE service_order_id = :id ORDER BY recorded_at
CREATE INDEX ix_processing_stage_records_order
    ON processing_stage_records (service_order_id, recorded_at);

CREATE TRIGGER processing_stage_records_append_only
    BEFORE UPDATE OR DELETE ON processing_stage_records
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();


-- Order Change Request (ERD #25, BR-40). Simple level (decision 14/10/2026); no UC detail yet.
CREATE TABLE order_change_requests (
    id                        bigint         GENERATED BY DEFAULT AS IDENTITY,
    service_order_id          bigint         NOT NULL,
    requested_by_account_id   bigint         NOT NULL,
    change_type               varchar(30)    NOT NULL,
    description               varchar(1000)  NOT NULL,
    proposed_changes          jsonb,
    price_difference_vnd      bigint,
    status                    varchar(20)    NOT NULL DEFAULT 'PENDING',
    responded_by_account_id   bigint,
    responded_at              timestamptz,
    created_at                timestamptz    NOT NULL DEFAULT now(),
    updated_at                timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_change_requests PRIMARY KEY (id),
    CONSTRAINT ck_order_change_requests_type CHECK (change_type IN
        ('CHANGE_PACKAGE', 'ADD_ROLLS', 'REMOVE_ROLLS', 'CHANGE_REQUIREMENTS', 'OTHER')),
    CONSTRAINT ck_order_change_requests_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_order_change_requests_response CHECK ((status = 'PENDING') = (responded_at IS NULL)),
    CONSTRAINT fk_order_change_requests_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_order_change_requests_requester FOREIGN KEY (requested_by_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_order_change_requests_responder FOREIGN KEY (responded_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN order_change_requests.proposed_changes IS 'Free structure until BR-40 has a detailed UC; jsonb avoids a schema change while the content is unknown.';
