-- =====================================================================================
-- 6. MODERATION (ERD #48; UC49, UC50; BR-15; UH-29 - UH-32)
-- Reported content is identified by (target_type, target_id), like audit_logs: the targets live
-- in six tables and are never physically deleted (status REMOVED), so a dangling id cannot occur.
-- =====================================================================================

CREATE TABLE content_reports (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    reporter_account_id     bigint         NOT NULL,
    target_type             varchar(30)    NOT NULL,
    target_id               bigint         NOT NULL,
    violation_type          varchar(30)    NOT NULL,
    description             varchar(500),
    status                  varchar(20)    NOT NULL DEFAULT 'OPEN',
    moderation_action_id    bigint,
    handled_by_account_id   bigint,
    handled_at              timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_content_reports PRIMARY KEY (id),
    -- UC49: a post, a comment, a thread (and its answers), a review, a consignment listing.
    CONSTRAINT ck_content_reports_target CHECK (target_type IN (
        'PHOTO_FEED_POST', 'PHOTO_FEED_COMMENT', 'FORUM_THREAD', 'FORUM_ANSWER', 'LAB_REVIEW', 'CONSIGNMENT_LISTING')),
    CONSTRAINT ck_content_reports_violation CHECK (violation_type IN (
        'SPAM', 'FRAUD', 'INAPPROPRIATE_CONTENT', 'MISINFORMATION', 'COPYRIGHT_INFRINGEMENT', 'OTHER')),
    -- UC49: a description is mandatory for OTHER.
    CONSTRAINT ck_content_reports_description CHECK (violation_type <> 'OTHER' OR description IS NOT NULL),
    -- DISMISSED (kept, or bulk-dismissed as malicious, UH-29) / ACTIONED (hidden or removed).
    CONSTRAINT ck_content_reports_status CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED')),
    CONSTRAINT ck_content_reports_handled CHECK ((status = 'OPEN') = (handled_at IS NULL)),
    -- UC49: one report per user and piece of content.
    CONSTRAINT uq_content_reports_once UNIQUE (reporter_account_id, target_type, target_id),
    CONSTRAINT fk_content_reports_reporter FOREIGN KEY (reporter_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_content_reports_handler FOREIGN KEY (handled_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON TABLE content_reports IS 'UH-29: the report weight of a user is derived from how many of their reports were DISMISSED; not stored.';

-- SCR Moderator queue (UC50), grouped by target with the number of reports.
CREATE INDEX ix_content_reports_open ON content_reports (target_type, target_id) WHERE status = 'OPEN';
-- UC49: 20 reports per user per day; also "reports by the same person in a short period" (UC50).
CREATE INDEX ix_content_reports_reporter ON content_reports (reporter_account_id, created_at DESC);


-- One Moderator decision. Append-only; undoing a decision is a new RESTORE row (UH-31).
CREATE TABLE moderation_actions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    target_type             varchar(30)    NOT NULL,
    target_id               bigint         NOT NULL,
    decision                varchar(20)    NOT NULL,
    reason                  varchar(500),
    content_author_account_id bigint       NOT NULL,
    author_sanction         varchar(20)    NOT NULL DEFAULT 'NONE',
    reverts_action_id       bigint,
    moderator_account_id    bigint         NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_moderation_actions PRIMARY KEY (id),
    CONSTRAINT ck_moderation_actions_target CHECK (target_type IN (
        'PHOTO_FEED_POST', 'PHOTO_FEED_COMMENT', 'FORUM_THREAD', 'FORUM_ANSWER', 'LAB_REVIEW',
        'CONSIGNMENT_LISTING', 'EXPERT_ARTICLE')),
    CONSTRAINT ck_moderation_actions_decision CHECK (decision IN ('KEEP', 'HIDE', 'REMOVE', 'RESTORE')),
    -- UC50: a reason of 10-500 characters when hiding or removing; it is sent to the author.
    CONSTRAINT ck_moderation_actions_reason CHECK (
        decision NOT IN ('HIDE', 'REMOVE') OR (reason IS NOT NULL AND char_length(reason) >= 10)),
    -- UC50: warning, 7-day lock or 30-day lock of the author (escalates on repost, UH-30).
    CONSTRAINT ck_moderation_actions_sanction CHECK (author_sanction IN ('NONE', 'WARNING', 'LOCK_7_DAYS', 'LOCK_30_DAYS')),
    CONSTRAINT ck_moderation_actions_restore CHECK ((decision = 'RESTORE') = (reverts_action_id IS NOT NULL)),
    CONSTRAINT fk_moderation_actions_author FOREIGN KEY (content_author_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_moderation_actions_reverts FOREIGN KEY (reverts_action_id) REFERENCES moderation_actions (id),
    CONSTRAINT fk_moderation_actions_moderator FOREIGN KEY (moderator_account_id) REFERENCES user_accounts (id)
);

-- History of one piece of content, and the warning history of one author (UH-30 escalation).
CREATE INDEX ix_moderation_actions_target ON moderation_actions (target_type, target_id, created_at);
CREATE INDEX ix_moderation_actions_author ON moderation_actions (content_author_account_id, created_at DESC);

CREATE TRIGGER moderation_actions_append_only
    BEFORE UPDATE OR DELETE ON moderation_actions
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();

ALTER TABLE content_reports ADD CONSTRAINT fk_content_reports_action
    FOREIGN KEY (moderation_action_id) REFERENCES moderation_actions (id);


-- Temporary account lock decided by a Moderator (UC50: 7 or 30 days). Different from
-- user_accounts.status = LOCKED (Admin, indefinite, UC11) and from login_locked_until (failed
-- sign-ins). Sign-in and the JWT filter refuse an account with an active row here.
CREATE TABLE account_suspensions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_account_id         bigint         NOT NULL,
    moderation_action_id    bigint         NOT NULL,
    reason                  varchar(500)   NOT NULL,
    starts_at               timestamptz    NOT NULL DEFAULT now(),
    ends_at                 timestamptz    NOT NULL,
    lifted_at               timestamptz,
    lifted_by_account_id    bigint,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_account_suspensions PRIMARY KEY (id),
    CONSTRAINT ck_account_suspensions_period CHECK (ends_at > starts_at),
    -- UH-31: a lock can be lifted early when the decision is undone.
    CONSTRAINT ck_account_suspensions_lift CHECK ((lifted_at IS NULL) = (lifted_by_account_id IS NULL)),
    CONSTRAINT fk_account_suspensions_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_account_suspensions_action FOREIGN KEY (moderation_action_id) REFERENCES moderation_actions (id),
    CONSTRAINT fk_account_suspensions_lifter FOREIGN KEY (lifted_by_account_id) REFERENCES user_accounts (id)
);

-- Checked on every sign-in / request: WHERE user_account_id = :id AND lifted_at IS NULL AND ends_at > now()
CREATE INDEX ix_account_suspensions_active ON account_suspensions (user_account_id, ends_at) WHERE lifted_at IS NULL;
