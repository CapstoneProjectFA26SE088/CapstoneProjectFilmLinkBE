-- One shipment = one trip / waybill with the Delivery Partner, in either direction.
-- [Cluster 4] consignment deliveries will add consignment_sale_id and make service_order_id nullable.
CREATE TABLE shipments (
    id                    bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id      bigint        NOT NULL,
    direction             varchar(30)   NOT NULL,
    shipping_type         varchar(20)   NOT NULL,
    provider              varchar(30)   NOT NULL,
    integration_mode      varchar(10)   NOT NULL DEFAULT 'API',
    provider_order_code   varchar(100),
    status                varchar(20)   NOT NULL DEFAULT 'CREATED',
    estimated_fee_vnd     bigint,
    actual_fee_vnd        bigint,
    fee_payer             varchar(20)   NOT NULL DEFAULT 'PHOTOGRAPHER',
    cod_amount_vnd        bigint        NOT NULL DEFAULT 0,
    recipient_address_line varchar(255) NOT NULL,
    recipient_district    varchar(100)  NOT NULL,
    recipient_province    varchar(100)  NOT NULL,
    recipient_phone       varchar(15)   NOT NULL,
    driver_name           varchar(100),
    driver_phone          varchar(15),
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_shipments PRIMARY KEY (id),
    CONSTRAINT ck_shipments_direction CHECK (direction IN ('TO_LAB', 'RETURN_TO_PHOTOGRAPHER')),
    CONSTRAINT ck_shipments_type CHECK (shipping_type IN ('PICKUP', 'PARCEL_SHIPPING')),
    -- Provider is not chosen yet: free value (MOCK, GHN, GHTK, AHAMOVE, ...), not a CHECK list.
    -- R-04: API fails 3 times -> manual handover mode.
    CONSTRAINT ck_shipments_mode CHECK (integration_mode IN ('API', 'MANUAL')),
    CONSTRAINT ck_shipments_status CHECK (status IN
        ('CREATED', 'PICKING_UP', 'IN_TRANSIT', 'DELIVERED', 'FAILED', 'RETURNED', 'CANCELLED', 'LOST')),
    -- Fees come from the partner API: estimate at order creation, actual when the waybill is created.
    CONSTRAINT ck_shipments_fees CHECK (
        (estimated_fee_vnd IS NULL OR estimated_fee_vnd >= 0) AND (actual_fee_vnd IS NULL OR actual_fee_vnd >= 0)
        AND cod_amount_vnd >= 0),
    -- UC27: return fee paid by the Photographer unless the lab is at fault (UH-09).
    CONSTRAINT ck_shipments_fee_payer CHECK (fee_payer IN ('PHOTOGRAPHER', 'FILM_LAB', 'PLATFORM')),
    CONSTRAINT fk_shipments_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id)
);

-- Webhook lookup by the partner's code, and protection against creating it twice.
CREATE UNIQUE INDEX uq_shipments_provider_code
    ON shipments (provider, provider_order_code)
    WHERE provider_order_code IS NOT NULL;

-- Order detail (SCR-19) shows its shipments.
CREATE INDEX ix_shipments_order ON shipments (service_order_id);

-- Full status history from webhooks (UC21). Duplicate webhooks are ignored by the unique key.
CREATE TABLE shipment_status_events (
    id                    bigint        GENERATED BY DEFAULT AS IDENTITY,
    shipment_id           bigint        NOT NULL,
    status                varchar(20)   NOT NULL,
    provider_status_code  varchar(50)   NOT NULL,
    occurred_at           timestamptz   NOT NULL,
    raw_payload           jsonb,
    received_at           timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_shipment_status_events PRIMARY KEY (id),
    CONSTRAINT uq_shipment_status_events_dedup UNIQUE (shipment_id, provider_status_code, occurred_at),
    CONSTRAINT fk_shipment_status_events_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id)
);

CREATE TRIGGER shipment_status_events_append_only
    BEFORE UPDATE OR DELETE ON shipment_status_events
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();


-- Film Handover (ERD #22, BR-25): every point where the film changes hands, with evidence.
-- Append-only: this is the evidence used to decide Complaints.
CREATE TABLE film_handovers (
    id                      bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id        bigint        NOT NULL,
    shipment_id             bigint,
    handover_point          varchar(40)   NOT NULL,
    roll_count              smallint      NOT NULL,
    note                    varchar(500),
    performed_by_account_id bigint,
    performed_by_name       varchar(100),
    occurred_at             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_handovers PRIMARY KEY (id),
    CONSTRAINT ck_film_handovers_point CHECK (handover_point IN (
        'COLLECTED_FROM_PHOTOGRAPHER', 'HANDED_TO_PARTNER', 'RECEIVED_AT_LAB',
        'HANDED_BACK_TO_PARTNER', 'RETURNED_TO_PHOTOGRAPHER', 'COLLECTED_AT_LAB')),
    -- UC23: actual roll count 0 .. declared + 5.
    CONSTRAINT ck_film_handovers_roll_count CHECK (roll_count BETWEEN 0 AND 25),
    -- The person is an account (lab, photographer) or a named driver of the partner.
    CONSTRAINT ck_film_handovers_performer CHECK (performed_by_account_id IS NOT NULL OR performed_by_name IS NOT NULL),
    CONSTRAINT fk_film_handovers_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_film_handovers_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id),
    CONSTRAINT fk_film_handovers_performer FOREIGN KEY (performed_by_account_id) REFERENCES user_accounts (id)
);

-- SCR-19 / complaint handling: all handovers of one order.
CREATE INDEX ix_film_handovers_order ON film_handovers (service_order_id, occurred_at);

CREATE TRIGGER film_handovers_append_only
    BEFORE UPDATE OR DELETE ON film_handovers
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();

-- Evidence photos: UC23 1-10 condition photos, UC27 >= 1 photo.
CREATE TABLE film_handover_photos (
    id                 bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_handover_id   bigint        NOT NULL,
    blob_key           varchar(500)  NOT NULL,
    display_order      smallint      NOT NULL,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_handover_photos PRIMARY KEY (id),
    CONSTRAINT uq_film_handover_photos_order UNIQUE (film_handover_id, display_order),
    CONSTRAINT ck_film_handover_photos_order CHECK (display_order BETWEEN 1 AND 10),
    CONSTRAINT fk_film_handover_photos_handover FOREIGN KEY (film_handover_id) REFERENCES film_handovers (id)
);

CREATE TRIGGER film_handover_photos_append_only
    BEFORE UPDATE OR DELETE ON film_handover_photos
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();

