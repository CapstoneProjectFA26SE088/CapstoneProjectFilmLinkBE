-- =====================================================================================
-- 4. PRICE OFFER (ERD #34; UC47, UC48 price reduction, UC65 reduce at expiry; BR-52; UH-45)
-- History cannot be edited or deleted (UC47): only the response columns change, once.
-- =====================================================================================

CREATE TABLE price_offers (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_item_id     bigint         NOT NULL,
    purpose                 varchar(20)    NOT NULL DEFAULT 'INITIAL',
    round_number            smallint       NOT NULL,
    offered_by_party        varchar(10)    NOT NULL,
    offered_by_account_id   bigint         NOT NULL,
    price_vnd               bigint         NOT NULL,
    justification           varchar(1000)  NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'PENDING',
    response_due_at         timestamptz    NOT NULL,
    reminder_sent_at        timestamptz,
    responded_at            timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_price_offers PRIMARY KEY (id),
    -- INITIAL: before listing (UC47). PRICE_REDUCTION: lab asks the seller (UC48). EXPIRY: UC65.
    CONSTRAINT ck_price_offers_purpose CHECK (purpose IN ('INITIAL', 'PRICE_REDUCTION', 'EXPIRY_REDUCTION')),
    -- UC47: at most 3 negotiation rounds.
    CONSTRAINT ck_price_offers_round CHECK (round_number BETWEEN 1 AND 3),
    CONSTRAINT ck_price_offers_party CHECK (offered_by_party IN ('LAB', 'SELLER')),
    CONSTRAINT ck_price_offers_price CHECK (price_vnd BETWEEN 1 AND 500000000),
    -- UC47: the lab justifies with 20-1000 characters; a seller counter-offer reason is <= 500.
    CONSTRAINT ck_price_offers_justification CHECK (
        (offered_by_party = 'LAB' AND char_length(justification) BETWEEN 20 AND 1000)
        OR (offered_by_party = 'SELLER' AND char_length(justification) BETWEEN 1 AND 500)),
    -- COUNTERED = the other party answered with a new offer (next row). EXPIRED = no answer in 72 h.
    CONSTRAINT ck_price_offers_status CHECK (status IN ('PENDING', 'ACCEPTED', 'COUNTERED', 'REJECTED', 'EXPIRED', 'WITHDRAWN')),
    CONSTRAINT ck_price_offers_response CHECK ((status = 'PENDING') = (responded_at IS NULL)),
    CONSTRAINT uq_price_offers_round UNIQUE (consignment_item_id, purpose, round_number, offered_by_party),
    CONSTRAINT fk_price_offers_item FOREIGN KEY (consignment_item_id) REFERENCES consignment_items (id),
    CONSTRAINT fk_price_offers_author FOREIGN KEY (offered_by_account_id) REFERENCES user_accounts (id)
);

-- Non-screen #15 (daily): offers past their 72-hour deadline.
CREATE INDEX ix_price_offers_pending ON price_offers (response_due_at) WHERE status = 'PENDING';
CREATE INDEX ix_price_offers_item ON price_offers (consignment_item_id, created_at);

-- Only status, responded_at and reminder_sent_at may change; nothing is ever deleted.
CREATE FUNCTION trg_price_offers_immutable() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'price_offers history cannot be deleted (UC47)';
    END IF;
    IF NEW.consignment_item_id <> OLD.consignment_item_id OR NEW.purpose <> OLD.purpose
       OR NEW.round_number <> OLD.round_number OR NEW.offered_by_party <> OLD.offered_by_party
       OR NEW.offered_by_account_id <> OLD.offered_by_account_id OR NEW.price_vnd <> OLD.price_vnd
       OR NEW.justification <> OLD.justification OR NEW.response_due_at <> OLD.response_due_at
       OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'price_offers content cannot be edited (UC47)';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER price_offers_immutable
    BEFORE UPDATE OR DELETE ON price_offers
    FOR EACH ROW EXECUTE FUNCTION trg_price_offers_immutable();


-- =====================================================================================
-- 5. LISTING (ERD #35; UC48, UC61, UC65; BR-13, BR-51, BR-53; UH-32, UH-46)
-- =====================================================================================

CREATE TABLE consignment_listings (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_item_id         bigint         NOT NULL,
    film_lab_id                 bigint         NOT NULL,
    title                       varchar(150)   NOT NULL,
    description                 varchar(3000)  NOT NULL,
    price_vnd                   bigint         NOT NULL,
    is_pickup_at_lab            boolean        NOT NULL DEFAULT true,
    is_delivery_available       boolean        NOT NULL DEFAULT false,
    status                      varchar(30)    NOT NULL DEFAULT 'DRAFT',
    consignment_started_at      timestamptz    NOT NULL,
    expires_at                  timestamptz    NOT NULL,
    extension_count             smallint       NOT NULL DEFAULT 0,
    reminder_sent_at            timestamptz,
    expiry_response_due_at      timestamptz,
    expiry_choice               varchar(20),
    published_at                timestamptz,
    hidden_reason               varchar(500),
    version                     integer        NOT NULL DEFAULT 0,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_listings PRIMARY KEY (id),
    CONSTRAINT uq_consignment_listings_item UNIQUE (consignment_item_id),
    CONSTRAINT ck_consignment_listings_title CHECK (char_length(title) BETWEEN 10 AND 150),
    CONSTRAINT ck_consignment_listings_description CHECK (char_length(description) BETWEEN 50 AND 3000),
    CONSTRAINT ck_consignment_listings_price CHECK (price_vnd BETWEEN 1 AND 500000000),
    -- BR-14 / UC48: at least one handover method.
    CONSTRAINT ck_consignment_listings_handover CHECK (is_pickup_at_lab OR is_delivery_available),
    -- UC48 statuses; REMOVED = taken down by a Moderator (UH-32), the item goes back to the seller.
    CONSTRAINT ck_consignment_listings_status CHECK (status IN (
        'DRAFT', 'ON_SALE', 'LOCKED', 'SOLD', 'HIDDEN', 'AWAITING_COLLECTION', 'REMOVED')),
    CONSTRAINT ck_consignment_listings_published CHECK (status = 'DRAFT' OR published_at IS NOT NULL),
    -- BR-53: 60 days, extended by 30 at a time.
    CONSTRAINT ck_consignment_listings_period CHECK (expires_at > consignment_started_at),
    CONSTRAINT ck_consignment_listings_extensions CHECK (extension_count >= 0),
    CONSTRAINT ck_consignment_listings_expiry_choice CHECK (
        expiry_choice IS NULL OR expiry_choice IN ('EXTEND', 'REDUCE_PRICE', 'TAKE_BACK')),
    CONSTRAINT ck_consignment_listings_hidden CHECK (status NOT IN ('HIDDEN', 'REMOVED') OR hidden_reason IS NOT NULL),
    CONSTRAINT fk_consignment_listings_item FOREIGN KEY (consignment_item_id) REFERENCES consignment_items (id),
    CONSTRAINT fk_consignment_listings_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id)
);

COMMENT ON COLUMN consignment_listings.film_lab_id IS 'Copy of the holding lab (item -> booking -> lab) so that search and the lab screen need no double join.';
COMMENT ON COLUMN consignment_listings.price_vnd IS 'Agreed price (UC47). Not edited directly: a reduction goes through a price_offers row confirmed by the seller.';
COMMENT ON COLUMN consignment_listings.version IS 'UH-46: two buyers at once - optimistic locking keeps only the first.';

-- UC61 public search: ON_SALE listings, newest first (filters on price/type/grade/lab follow).
CREATE INDEX ix_consignment_listings_on_sale
    ON consignment_listings (published_at DESC) WHERE status = 'ON_SALE';

-- Lab screen: listings of one lab by status.
CREATE INDEX ix_consignment_listings_lab ON consignment_listings (film_lab_id, status);

-- Non-screen #25 / #26 (daily): reminder on day 45 and expiry at day 60.
CREATE INDEX ix_consignment_listings_expiry ON consignment_listings (expires_at) WHERE status = 'ON_SALE';
