-- Moderated content (posts, comments, threads, answers, reviews, listings) is never deleted:
-- status VISIBLE / HIDDEN / REMOVED, so that a Moderator decision can be undone (UC50, UH-31).

-- =====================================================================================
-- 1. LAB REVIEW (ERD #40; UC37, UC38; BR-33)
-- =====================================================================================

CREATE TABLE lab_reviews (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    service_order_id        bigint         NOT NULL,
    film_lab_id             bigint         NOT NULL,
    author_account_id       bigint         NOT NULL,
    rating                  smallint       NOT NULL,
    content                 varchar(2000)  NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'VISIBLE',
    lab_reply               varchar(2000),
    lab_replied_at          timestamptz,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_lab_reviews PRIMARY KEY (id),
    -- BR-33: one review per Service Order (the order must be CLOSED - checked by the service).
    CONSTRAINT uq_lab_reviews_order UNIQUE (service_order_id),
    CONSTRAINT ck_lab_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_lab_reviews_content CHECK (char_length(content) BETWEEN 20 AND 2000),
    -- UC37 / UC50: a HIDDEN or REMOVED review is excluded from the lab's average rating.
    CONSTRAINT ck_lab_reviews_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED')),
    -- [TBC] UC38 (Should) reply length not specified yet.
    CONSTRAINT ck_lab_reviews_reply CHECK ((lab_reply IS NULL) = (lab_replied_at IS NULL)),
    CONSTRAINT fk_lab_reviews_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_lab_reviews_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_lab_reviews_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN lab_reviews.film_lab_id IS 'Copy of service_orders.film_lab_id: the rating average per lab (UC17, UC18) reads this table alone.';
COMMENT ON COLUMN lab_reviews.created_at IS 'UC37: editable for 7 days after posting (LAB_REVIEW_EDIT_DAYS), checked by the service.';

-- Lab detail (SCR-11), rating average for search / recommendation, newest first.
CREATE INDEX ix_lab_reviews_lab ON lab_reviews (film_lab_id, created_at DESC) WHERE status = 'VISIBLE';

-- UC37: at most 5 photos.
CREATE TABLE lab_review_photos (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    lab_review_id           bigint         NOT NULL,
    blob_key                varchar(500)   NOT NULL,
    display_order           smallint       NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_lab_review_photos PRIMARY KEY (id),
    CONSTRAINT uq_lab_review_photos_order UNIQUE (lab_review_id, display_order),
    CONSTRAINT ck_lab_review_photos_order CHECK (display_order BETWEEN 1 AND 5),
    CONSTRAINT fk_lab_review_photos_review FOREIGN KEY (lab_review_id) REFERENCES lab_reviews (id) ON DELETE CASCADE
);


-- =====================================================================================
-- 2. PHOTO FEED (ERD #41, #42; UC39 - Tier Should)
-- =====================================================================================

CREATE TABLE photo_feed_posts (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    author_account_id       bigint         NOT NULL,
    caption                 varchar(2000),
    film_stock_id           bigint,
    film_stock_name_text    varchar(100),
    camera                  varchar(100),
    film_lab_id             bigint,
    status                  varchar(20)    NOT NULL DEFAULT 'VISIBLE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_photo_feed_posts PRIMARY KEY (id),
    -- UC39: film stock from the catalogue or typed freely (same rule as film_rolls), optional.
    CONSTRAINT ck_photo_feed_posts_stock CHECK (num_nonnulls(film_stock_id, film_stock_name_text) <= 1),
    CONSTRAINT ck_photo_feed_posts_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED')),
    CONSTRAINT fk_photo_feed_posts_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_photo_feed_posts_stock FOREIGN KEY (film_stock_id) REFERENCES film_stocks (id),
    CONSTRAINT fk_photo_feed_posts_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id)
);

-- Feed (SCR-27), newest first; author's profile page.
CREATE INDEX ix_photo_feed_posts_feed ON photo_feed_posts (created_at DESC) WHERE status = 'VISIBLE';
CREATE INDEX ix_photo_feed_posts_author ON photo_feed_posts (author_account_id, created_at DESC);

-- [TBC] UC39 photo count not specified; 1-10 per post, <= 10 MB each (UC40 input limit).
CREATE TABLE photo_feed_post_images (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    photo_feed_post_id      bigint         NOT NULL,
    blob_key                varchar(500)   NOT NULL,
    display_order           smallint       NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_photo_feed_post_images PRIMARY KEY (id),
    CONSTRAINT uq_photo_feed_post_images_order UNIQUE (photo_feed_post_id, display_order),
    CONSTRAINT ck_photo_feed_post_images_order CHECK (display_order BETWEEN 1 AND 10),
    CONSTRAINT fk_photo_feed_post_images_post FOREIGN KEY (photo_feed_post_id) REFERENCES photo_feed_posts (id) ON DELETE CASCADE
);

-- "likes" is a many-to-many relationship on the ERD, not an entity.
CREATE TABLE photo_feed_post_likes (
    photo_feed_post_id      bigint         NOT NULL,
    user_account_id         bigint         NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_photo_feed_post_likes PRIMARY KEY (photo_feed_post_id, user_account_id),
    CONSTRAINT fk_photo_feed_post_likes_post FOREIGN KEY (photo_feed_post_id) REFERENCES photo_feed_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_photo_feed_post_likes_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);

CREATE TABLE photo_feed_comments (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    photo_feed_post_id      bigint         NOT NULL,
    author_account_id       bigint         NOT NULL,
    content                 varchar(1000)  NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'VISIBLE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_photo_feed_comments PRIMARY KEY (id),
    -- [TBC] length not specified by UC39.
    CONSTRAINT ck_photo_feed_comments_content CHECK (char_length(content) BETWEEN 1 AND 1000),
    CONSTRAINT ck_photo_feed_comments_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED')),
    CONSTRAINT fk_photo_feed_comments_post FOREIGN KEY (photo_feed_post_id) REFERENCES photo_feed_posts (id),
    CONSTRAINT fk_photo_feed_comments_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_photo_feed_comments_post ON photo_feed_comments (photo_feed_post_id, created_at);
