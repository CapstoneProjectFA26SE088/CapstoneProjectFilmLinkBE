-- =====================================================================================
-- 3. LAB REGISTRATION & EXPERT UPGRADE APPLICATIONS (UC07-UC10)
-- =====================================================================================

CREATE TABLE lab_registration_applications (
    id                       bigint        GENERATED BY DEFAULT AS IDENTITY,
    application_code         varchar(20)   NOT NULL,
    lab_name                 varchar(150)  NOT NULL,
    tax_code                 varchar(14)   NOT NULL,
    address_line             varchar(255)  NOT NULL,
    district                 varchar(100)  NOT NULL,
    province                 varchar(100)  NOT NULL,
    latitude                 numeric(9,6),
    longitude                numeric(9,6),
    contact_email            varchar(255)  NOT NULL,
    contact_phone            varchar(15)   NOT NULL,
    status                   varchar(20)   NOT NULL DEFAULT 'PENDING_REVIEW',
    is_duplicate_suspected   boolean       NOT NULL DEFAULT false,
    rejection_reason         varchar(500),
    reviewed_by_account_id   bigint,
    reviewed_at              timestamptz,
    version                  integer       NOT NULL DEFAULT 0,
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_lab_registration_applications PRIMARY KEY (id),
    -- MSG14: reference code given to the applicant for tracking.
    CONSTRAINT uq_lab_registration_applications_code UNIQUE (application_code),
    CONSTRAINT ck_lab_registration_applications_name CHECK (char_length(lab_name) BETWEEN 2 AND 150),
    -- Vietnamese tax code: 10 digits, or 10 digits + '-' + 3-digit branch suffix.
    CONSTRAINT ck_lab_registration_applications_tax_code CHECK (tax_code ~ '^[0-9]{10}(-[0-9]{3})?$'),
    -- UH-06: if geocoding fails both coordinates stay NULL; never only one of them.
    CONSTRAINT ck_lab_registration_applications_coordinates CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)),
    CONSTRAINT ck_lab_registration_applications_status CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    -- UC08: a rejection needs a reason of 10-500 characters.
    CONSTRAINT ck_lab_registration_applications_rejection CHECK (
        (status = 'REJECTED') = (rejection_reason IS NOT NULL)
        AND (rejection_reason IS NULL OR char_length(rejection_reason) >= 10)),
    CONSTRAINT ck_lab_registration_applications_review CHECK (
        (status = 'PENDING_REVIEW') = (reviewed_at IS NULL)),
    CONSTRAINT fk_lab_registration_applications_reviewer FOREIGN KEY (reviewed_by_account_id)
        REFERENCES user_accounts (id)
);

COMMENT ON COLUMN lab_registration_applications.version IS 'UC08: optimistic locking when two Admins process the same application.';
COMMENT ON COLUMN lab_registration_applications.is_duplicate_suspected IS 'UH-02: same tax code or address as an existing lab; still accepted, flagged for the Admin.';

-- Legal documents of an application: 1..5 files, PDF or image, <= 10 MB each (UC07).
CREATE TABLE lab_registration_documents (
    id                               bigint        GENERATED BY DEFAULT AS IDENTITY,
    lab_registration_application_id  bigint        NOT NULL,
    file_name                        varchar(255)  NOT NULL,
    blob_key                         varchar(500)  NOT NULL,
    content_type                     varchar(100)  NOT NULL,
    size_bytes                       bigint        NOT NULL,
    created_at                       timestamptz   NOT NULL DEFAULT now(),
    updated_at                       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_lab_registration_documents PRIMARY KEY (id),
    CONSTRAINT ck_lab_registration_documents_type CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    CONSTRAINT ck_lab_registration_documents_size CHECK (size_bytes BETWEEN 1 AND 10485760),
    CONSTRAINT fk_lab_registration_documents_application FOREIGN KEY (lab_registration_application_id)
        REFERENCES lab_registration_applications (id) ON DELETE CASCADE
);

-- Many-to-many: services, processes and formats the applicant intends to offer (UC07).
CREATE TABLE lab_registration_application_service_types (
    lab_registration_application_id  bigint  NOT NULL,
    service_type_id                  bigint  NOT NULL,
    CONSTRAINT pk_lab_registration_application_service_types
        PRIMARY KEY (lab_registration_application_id, service_type_id),
    CONSTRAINT fk_lrast_application FOREIGN KEY (lab_registration_application_id)
        REFERENCES lab_registration_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_lrast_service_type FOREIGN KEY (service_type_id)
        REFERENCES service_types (id)
);

CREATE TABLE lab_registration_application_film_processes (
    lab_registration_application_id  bigint  NOT NULL,
    film_process_id                  bigint  NOT NULL,
    CONSTRAINT pk_lab_registration_application_film_processes
        PRIMARY KEY (lab_registration_application_id, film_process_id),
    CONSTRAINT fk_lrafp_application FOREIGN KEY (lab_registration_application_id)
        REFERENCES lab_registration_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_lrafp_film_process FOREIGN KEY (film_process_id)
        REFERENCES film_processes (id)
);

CREATE TABLE lab_registration_application_film_formats (
    lab_registration_application_id  bigint  NOT NULL,
    film_format_id                   bigint  NOT NULL,
    CONSTRAINT pk_lab_registration_application_film_formats
        PRIMARY KEY (lab_registration_application_id, film_format_id),
    CONSTRAINT fk_lraff_application FOREIGN KEY (lab_registration_application_id)
        REFERENCES lab_registration_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_lraff_film_format FOREIGN KEY (film_format_id)
        REFERENCES film_formats (id)
);


-- Expert Upgrade Application (ERD #7, UC09-UC10, Tier Should). Field list [TBC]: the
-- detailed specification of UC09/UC10 is planned for Review 2.
CREATE TABLE expert_upgrade_applications (
    id                       bigint         GENERATED BY DEFAULT AS IDENTITY,
    applicant_account_id     bigint         NOT NULL,
    portfolio_url            varchar(500)   NOT NULL,
    experience_summary       varchar(2000)  NOT NULL,
    status                   varchar(20)    NOT NULL DEFAULT 'PENDING_REVIEW',
    rejection_reason         varchar(500),
    reviewed_by_account_id   bigint,
    reviewed_at              timestamptz,
    version                  integer        NOT NULL DEFAULT 0,
    created_at               timestamptz    NOT NULL DEFAULT now(),
    updated_at               timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_expert_upgrade_applications PRIMARY KEY (id),
    CONSTRAINT ck_expert_upgrade_applications_status CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_expert_upgrade_applications_rejection CHECK (
        (status = 'REJECTED') = (rejection_reason IS NOT NULL)),
    CONSTRAINT ck_expert_upgrade_applications_review CHECK (
        (status = 'PENDING_REVIEW') = (reviewed_at IS NULL)),
    CONSTRAINT fk_expert_upgrade_applications_applicant FOREIGN KEY (applicant_account_id)
        REFERENCES user_accounts (id),
    CONSTRAINT fk_expert_upgrade_applications_reviewer FOREIGN KEY (reviewed_by_account_id)
        REFERENCES user_accounts (id)
);

-- [TBC] At most one pending application per account. Also serves "my pending application".
CREATE UNIQUE INDEX uq_expert_upgrade_applications_one_pending
    ON expert_upgrade_applications (applicant_account_id)
    WHERE status = 'PENDING_REVIEW';
