-- Archive entry of one roll: Full-resolution Link (per roll, decision 14/10/2026) and the
-- metadata the Photographer adds (UC28). Owned by the archive domain, not by order.
CREATE TABLE archive_rolls (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_roll_id                bigint         NOT NULL,
    full_resolution_link        varchar(1000)  NOT NULL,
    link_verified_at            timestamptz    NOT NULL,
    frame_count_discrepancy_note varchar(500),
    camera                      varchar(100),
    lens                        varchar(100),
    shot_on                     date,
    location                    varchar(200),
    note                        varchar(1000),
    delivered_at                timestamptz    NOT NULL DEFAULT now(),
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_archive_rolls PRIMARY KEY (id),
    CONSTRAINT uq_archive_rolls_roll UNIQUE (film_roll_id),
    CONSTRAINT ck_archive_rolls_link CHECK (full_resolution_link ~* '^https?://'),
    CONSTRAINT fk_archive_rolls_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id)
);

-- Scan File (ERD #23): one Preview Scan image (BR-08: full-resolution files are NOT stored).
CREATE TABLE scan_files (
    id               bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_roll_id     bigint        NOT NULL,
    scan_job_id      bigint,
    frame_number     smallint,
    blob_key         varchar(500)  NOT NULL,
    size_bytes       integer       NOT NULL,
    width_px         smallint      NOT NULL,
    height_px        smallint      NOT NULL,
    checksum_sha256  char(64)      NOT NULL,
    is_current       boolean       NOT NULL DEFAULT true,
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_scan_files PRIMARY KEY (id),
    CONSTRAINT uq_scan_files_blob UNIQUE (blob_key),
    -- UC26: JPG, longest edge <= 2048 px, <= 5 MB.
    CONSTRAINT ck_scan_files_size CHECK (size_bytes BETWEEN 1 AND 5242880),
    CONSTRAINT ck_scan_files_dimensions CHECK (width_px BETWEEN 1 AND 2048 AND height_px BETWEEN 1 AND 2048),
    CONSTRAINT ck_scan_files_frame CHECK (frame_number IS NULL OR frame_number BETWEEN 0 AND 100),
    CONSTRAINT fk_scan_files_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id),
    CONSTRAINT fk_scan_files_job FOREIGN KEY (scan_job_id) REFERENCES scan_jobs (id)
);

COMMENT ON COLUMN scan_files.checksum_sha256 IS 'NFR-CAP-03: files must be retrieved with the correct checksum.';
COMMENT ON COLUMN scan_files.is_current IS 'false for previews replaced by a re-scan (BR-27); kept for complaint evidence.';

-- SCR-23 images of one roll; also the per-Photographer storage quota sum (UC28, 10 GB).
CREATE INDEX ix_scan_files_roll ON scan_files (film_roll_id) WHERE is_current;

-- Rescan Request (ERD #24, BR-27): at most one per order, within 7 days of the previews.
CREATE TABLE rescan_requests (
    id                        bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_order_id          bigint        NOT NULL,
    requested_by_account_id   bigint        NOT NULL,
    reason                    varchar(500)  NOT NULL,
    status                    varchar(20)   NOT NULL DEFAULT 'PENDING',
    lab_response_note         varchar(500),
    resolved_at               timestamptz,
    created_at                timestamptz   NOT NULL DEFAULT now(),
    updated_at                timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_rescan_requests PRIMARY KEY (id),
    CONSTRAINT uq_rescan_requests_order UNIQUE (service_order_id),
    -- Not agreed between the parties -> ESCALATED to the Admin (UH-13).
    CONSTRAINT ck_rescan_requests_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'ESCALATED', 'COMPLETED')),
    CONSTRAINT fk_rescan_requests_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_rescan_requests_requester FOREIGN KEY (requested_by_account_id) REFERENCES user_accounts (id)
);

-- Many-to-many: which rolls of the order must be re-scanned.
CREATE TABLE rescan_request_rolls (
    rescan_request_id  bigint  NOT NULL,
    film_roll_id       bigint  NOT NULL,
    CONSTRAINT pk_rescan_request_rolls PRIMARY KEY (rescan_request_id, film_roll_id),
    CONSTRAINT fk_rrr_request FOREIGN KEY (rescan_request_id) REFERENCES rescan_requests (id) ON DELETE CASCADE,
    CONSTRAINT fk_rrr_roll FOREIGN KEY (film_roll_id) REFERENCES film_rolls (id)
);

ALTER TABLE scan_jobs ADD CONSTRAINT fk_scan_jobs_rescan
    FOREIGN KEY (rescan_request_id) REFERENCES rescan_requests (id);
