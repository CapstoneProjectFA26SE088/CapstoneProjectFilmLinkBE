-- AI Interaction (ERD #50): one call of an AI feature, with its result and the user's feedback.
-- Also the basis of the daily chatbot quota (UC19: 30 questions per user per day).
CREATE TABLE ai_interactions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_account_id         bigint,
    feature                 varchar(30)    NOT NULL,
    status                  varchar(20)    NOT NULL,
    is_fallback             boolean        NOT NULL DEFAULT false,
    model_name              varchar(100),
    request_payload         jsonb,
    response_payload        jsonb,
    error_message           varchar(1000),
    latency_ms              integer,
    prompt_tokens           integer,
    completion_tokens       integer,
    feedback                varchar(20),
    feedback_note           varchar(500),
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_ai_interactions PRIMARY KEY (id),
    CONSTRAINT ck_ai_interactions_feature CHECK (feature IN (
        'LAB_RECOMMENDATION', 'ADVISORY_CHATBOT', 'IMAGE_ANALYSIS', 'SCAN_QUALITY_ASSESSMENT')),
    -- FALLBACK = LLM quota / outage, rule-based answer shown with a label (UC18, UH-08).
    CONSTRAINT ck_ai_interactions_status CHECK (status IN ('SUCCEEDED', 'FAILED', 'FALLBACK', 'REFUSED')),
    CONSTRAINT ck_ai_interactions_feedback CHECK (feedback IS NULL OR feedback IN ('HELPFUL', 'NOT_HELPFUL')),
    CONSTRAINT ck_ai_interactions_numbers CHECK (
        (latency_ms IS NULL OR latency_ms >= 0) AND (prompt_tokens IS NULL OR prompt_tokens >= 0)
        AND (completion_tokens IS NULL OR completion_tokens >= 0)),
    -- NULL for background features (image analysis, scan quality) triggered by the system.
    CONSTRAINT fk_ai_interactions_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);

-- UC19 quota: SELECT count(*) WHERE user_account_id = :me AND feature = 'ADVISORY_CHATBOT' AND created_at >= today
CREATE INDEX ix_ai_interactions_user_feature ON ai_interactions (user_account_id, feature, created_at DESC);
-- Cost and error monitoring (UC56 dashboard) by time.
CREATE INDEX ix_ai_interactions_created_brin ON ai_interactions USING brin (created_at);


-- Advisory Chatbot conversation (UC19): the last 10 turns of a session are sent as context.
CREATE TABLE chatbot_sessions (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    user_account_id         bigint         NOT NULL,
    title                   varchar(150),
    last_message_at         timestamptz    NOT NULL DEFAULT now(),
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_chatbot_sessions PRIMARY KEY (id),
    CONSTRAINT fk_chatbot_sessions_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_chatbot_sessions_user ON chatbot_sessions (user_account_id, last_message_at DESC);

CREATE TABLE chatbot_messages (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    chatbot_session_id      bigint         NOT NULL,
    sender                  varchar(10)    NOT NULL,
    content                 text           NOT NULL,
    citations               jsonb,
    ai_interaction_id       bigint,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_chatbot_messages PRIMARY KEY (id),
    CONSTRAINT ck_chatbot_messages_sender CHECK (sender IN ('USER', 'ASSISTANT')),
    -- UC19: a question is 5-1000 characters.
    CONSTRAINT ck_chatbot_messages_question CHECK (sender <> 'USER' OR char_length(content) BETWEEN 5 AND 1000),
    -- UC19: at most 3 citations, each pointing at an Expert Article (BR-29).
    CONSTRAINT ck_chatbot_messages_citations CHECK (
        citations IS NULL OR (sender = 'ASSISTANT' AND jsonb_typeof(citations) = 'array' AND jsonb_array_length(citations) <= 3)),
    CONSTRAINT fk_chatbot_messages_session FOREIGN KEY (chatbot_session_id) REFERENCES chatbot_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_chatbot_messages_interaction FOREIGN KEY (ai_interaction_id) REFERENCES ai_interactions (id)
);

COMMENT ON COLUMN chatbot_messages.citations IS 'Array of {"expertArticleId": n, "title": "..."}; at most 3.';

-- Last 10 turns of a session.
CREATE INDEX ix_chatbot_messages_session ON chatbot_messages (chatbot_session_id, created_at DESC);


-- Image Analysis (UC40, non-screen #12): film stock + style tags + a vector for similar photos.
-- Runs on a Preview Scan of the archive (Core) or on a Photo Feed image (Should).
-- With OpenAI (no image embedding endpoint), the vision model writes a short description and
-- that text is embedded with the text model - same storage rule as knowledge_base_chunks.
CREATE TABLE image_analyses (
    id                          bigint         GENERATED BY DEFAULT AS IDENTITY,
    scan_file_id                bigint,
    photo_feed_post_image_id    bigint,
    status                      varchar(20)    NOT NULL DEFAULT 'PENDING',
    attempt_count               smallint       NOT NULL DEFAULT 0,
    last_error                  varchar(1000),
    predicted_film_stock_id     bigint,
    film_stock_confidence       numeric(4,3),
    style_tags                  text[],
    is_auto_tagged              boolean        NOT NULL DEFAULT false,
    description                 text,
    corrected_film_stock_id     bigint,
    corrected_by_account_id     bigint,
    corrected_at                timestamptz,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_image_analyses PRIMARY KEY (id),
    CONSTRAINT ck_image_analyses_source CHECK (num_nonnulls(scan_file_id, photo_feed_post_image_id) = 1),
    -- RETRYING: the vision service was down, the task is on the retry queue (UH-08).
    CONSTRAINT ck_image_analyses_status CHECK (status IN ('PENDING', 'RETRYING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_image_analyses_confidence CHECK (film_stock_confidence IS NULL OR film_stock_confidence BETWEEN 0 AND 1),
    -- Auto-tag only above IMAGE_ANALYSIS_CONFIDENCE_THRESHOLD; below it is a suggestion (UC40).
    CONSTRAINT ck_image_analyses_auto_tag CHECK (NOT is_auto_tagged OR predicted_film_stock_id IS NOT NULL),
    -- UC40: the owner's correction is kept as a labelled pair for later tuning.
    CONSTRAINT ck_image_analyses_correction CHECK (
        (corrected_film_stock_id IS NULL) = (corrected_at IS NULL)
        AND (corrected_at IS NULL) = (corrected_by_account_id IS NULL)),
    CONSTRAINT uq_image_analyses_scan UNIQUE (scan_file_id),
    CONSTRAINT uq_image_analyses_feed_image UNIQUE (photo_feed_post_image_id),
    CONSTRAINT fk_image_analyses_scan FOREIGN KEY (scan_file_id) REFERENCES scan_files (id),
    CONSTRAINT fk_image_analyses_feed_image FOREIGN KEY (photo_feed_post_image_id) REFERENCES photo_feed_post_images (id) ON DELETE CASCADE,
    CONSTRAINT fk_image_analyses_predicted FOREIGN KEY (predicted_film_stock_id) REFERENCES film_stocks (id),
    CONSTRAINT fk_image_analyses_corrected FOREIGN KEY (corrected_film_stock_id) REFERENCES film_stocks (id),
    CONSTRAINT fk_image_analyses_corrector FOREIGN KEY (corrected_by_account_id) REFERENCES user_accounts (id)
);

-- Retry queue.
CREATE INDEX ix_image_analyses_pending ON image_analyses (updated_at) WHERE status IN ('PENDING', 'RETRYING');

-- Scan Quality Assessment (UC57 - Should, BR-30, QD-015): internal warning for the lab only,
-- never shown to the Photographer, never blocks delivery.
CREATE TABLE scan_quality_assessments (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    scan_file_id            bigint         NOT NULL,
    sharpness_score         numeric(10,2)  NOT NULL,
    is_blurry               boolean        NOT NULL,
    exposure_assessment     varchar(20)    NOT NULL,
    is_resolution_sufficient boolean       NOT NULL,
    has_warning             boolean        NOT NULL,
    assessed_at             timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_scan_quality_assessments PRIMARY KEY (id),
    CONSTRAINT uq_scan_quality_assessments_scan UNIQUE (scan_file_id),
    -- Laplacian variance (sharpness) and histogram (exposure), UC57.
    CONSTRAINT ck_scan_quality_assessments_sharpness CHECK (sharpness_score >= 0),
    CONSTRAINT ck_scan_quality_assessments_exposure CHECK (exposure_assessment IN ('UNDEREXPOSED', 'CORRECT', 'OVEREXPOSED')),
    CONSTRAINT ck_scan_quality_assessments_warning CHECK (
        has_warning = (is_blurry OR exposure_assessment <> 'CORRECT' OR NOT is_resolution_sufficient)),
    CONSTRAINT fk_scan_quality_assessments_scan FOREIGN KEY (scan_file_id) REFERENCES scan_files (id)
);
