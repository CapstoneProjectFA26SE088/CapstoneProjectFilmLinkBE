-- Film Lab (ERD #8). Created only when a Lab Registration Application is approved (BR-03),
-- so "profile approved by the Admin" (BR-34) is implied by the row existing.
CREATE TABLE film_labs (
    id                               bigint         GENERATED BY DEFAULT AS IDENTITY,
    owner_account_id                 bigint         NOT NULL,
    lab_registration_application_id  bigint         NOT NULL,
    lab_name                         varchar(150)   NOT NULL,
    description                      varchar(2000),
    address_line                     varchar(255)   NOT NULL,
    district                         varchar(100)   NOT NULL,
    province                         varchar(100)   NOT NULL,
    latitude                         numeric(9,6),
    longitude                        numeric(9,6),
    contact_email                    varchar(255)   NOT NULL,
    contact_phone                    varchar(15)    NOT NULL,
    is_accepting_orders              boolean        NOT NULL DEFAULT false,
    qc_buffer_hours                  smallint       NOT NULL DEFAULT 4,
    express_daily_cap_percent        smallint,
    created_at                       timestamptz    NOT NULL DEFAULT now(),
    updated_at                       timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT pk_film_labs PRIMARY KEY (id),
    -- One Film Lab Owner account manages exactly one Film Lab, and vice versa (LI-10).
    CONSTRAINT uq_film_labs_owner UNIQUE (owner_account_id),
    -- One approved application results in at most one Film Lab.
    CONSTRAINT uq_film_labs_application UNIQUE (lab_registration_application_id),
    CONSTRAINT ck_film_labs_name CHECK (char_length(lab_name) BETWEEN 2 AND 150),
    -- UC12: 50-2000 characters once filled in (a newly approved lab has none yet).
    CONSTRAINT ck_film_labs_description CHECK (description IS NULL OR char_length(description) BETWEEN 50 AND 2000),
    CONSTRAINT ck_film_labs_coordinates CHECK (
        (latitude IS NULL AND longitude IS NULL)
        OR (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)),
    -- BR-60 / UC68: QC buffer in working hours, used in the promised return date formula.
    CONSTRAINT ck_film_labs_qc_buffer CHECK (qc_buffer_hours BETWEEN 0 AND 48),
    -- BR-61: max share of Express-tier orders per day; NULL = no cap.
    CONSTRAINT ck_film_labs_express_cap CHECK (express_daily_cap_percent IS NULL OR express_daily_cap_percent BETWEEN 1 AND 100),
    CONSTRAINT fk_film_labs_owner FOREIGN KEY (owner_account_id)
        REFERENCES user_accounts (id),
    CONSTRAINT fk_film_labs_application FOREIGN KEY (lab_registration_application_id)
        REFERENCES lab_registration_applications (id)
);

COMMENT ON COLUMN film_labs.is_accepting_orders IS 'UC12 order acceptance status. Default false: a new lab is not searchable until its owner opens it (BR-34).';
-- Rating, review count and sanction level are NOT stored here: UC17 computes them per query
-- from lab_reviews (cluster 5) and sanctions (cluster 3). At NFR-CAP-02 scale (~20 labs) the
-- aggregation is cheap, and a stored copy would need updating on every review write, review
-- hiding (UC50), sanction and reinstatement (BR-21).
-- Supported Film Processes / Formats are NOT stored either: they are derived from the
-- on-sale service_packages of the lab (decision 14/10/2026; UC12 wording to be updated).

-- Cross-table rule a CHECK cannot express: the owner must hold the FILM_LAB_OWNER role.
CREATE FUNCTION trg_film_labs_owner_role() RETURNS trigger AS $$
BEGIN
    IF (SELECT role FROM user_accounts WHERE id = NEW.owner_account_id) <> 'FILM_LAB_OWNER' THEN
        RAISE EXCEPTION 'film_labs.owner_account_id % must reference a FILM_LAB_OWNER account', NEW.owner_account_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER film_labs_owner_role
    BEFORE INSERT OR UPDATE OF owner_account_id ON film_labs
    FOR EACH ROW EXECUTE FUNCTION trg_film_labs_owner_role();

-- Opening hours per day of week (UC12). One row per lab and day.
CREATE TABLE film_lab_opening_hours (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id  bigint       NOT NULL,
    day_of_week  smallint     NOT NULL,
    is_closed    boolean      NOT NULL DEFAULT false,
    opens_at     time,
    closes_at    time,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_lab_opening_hours PRIMARY KEY (id),
    CONSTRAINT uq_film_lab_opening_hours_day UNIQUE (film_lab_id, day_of_week),
    -- ISO-8601: 1 = Monday ... 7 = Sunday.
    CONSTRAINT ck_film_lab_opening_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_film_lab_opening_hours_times CHECK (
        (is_closed AND opens_at IS NULL AND closes_at IS NULL)
        OR (NOT is_closed AND opens_at IS NOT NULL AND closes_at IS NOT NULL AND opens_at < closes_at)),
    CONSTRAINT fk_film_lab_opening_hours_lab FOREIGN KEY (film_lab_id)
        REFERENCES film_labs (id) ON DELETE CASCADE
);

-- Sample images (UC12): at most 20 per lab, ordered.
CREATE TABLE film_lab_images (
    id             bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id    bigint        NOT NULL,
    blob_key       varchar(500)  NOT NULL,
    display_order  smallint      NOT NULL,
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_lab_images PRIMARY KEY (id),
    CONSTRAINT uq_film_lab_images_order UNIQUE (film_lab_id, display_order),
    CONSTRAINT ck_film_lab_images_order CHECK (display_order BETWEEN 1 AND 20),
    CONSTRAINT fk_film_lab_images_lab FOREIGN KEY (film_lab_id)
        REFERENCES film_labs (id) ON DELETE CASCADE
);

-- Scanning equipment of UC12 is not a separate list: the public profile shows the machines
-- of type SCANNER with their model_name (table machines, cluster 2; BR-57 guarantees >= 1).

-- Service Package (ERD #10, UC13). The Price List is the set of on-sale packages of a lab.
CREATE TABLE service_packages (
    id                                bigint        GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id                       bigint        NOT NULL,
    package_name                      varchar(150)  NOT NULL,
    service_type_id                   bigint        NOT NULL,
    film_process_id                   bigint        NOT NULL,
    film_format_id                    bigint        NOT NULL,
    price_vnd                         bigint        NOT NULL,
    turnaround_days                   smallint      NOT NULL,
    is_push_pull_available            boolean       NOT NULL DEFAULT false,
    push_pull_surcharge_per_stop_vnd  bigint,
    express_surcharge_vnd             bigint,
    status                            varchar(20)   NOT NULL DEFAULT 'ON_SALE',
    created_at                        timestamptz   NOT NULL DEFAULT now(),
    updated_at                        timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_service_packages PRIMARY KEY (id),
    CONSTRAINT ck_service_packages_name CHECK (char_length(package_name) BETWEEN 2 AND 150),
    -- UC13: positive integer VND, maximum 50,000,000.
    CONSTRAINT ck_service_packages_price CHECK (price_vnd BETWEEN 1 AND 50000000),
    -- UC13: positive number of days, maximum 60.
    CONSTRAINT ck_service_packages_turnaround CHECK (turnaround_days BETWEEN 1 AND 60),
    CONSTRAINT ck_service_packages_push_pull CHECK (
        is_push_pull_available = (push_pull_surcharge_per_stop_vnd IS NOT NULL)
        AND (push_pull_surcharge_per_stop_vnd IS NULL OR push_pull_surcharge_per_stop_vnd > 0)),
    -- [TBC] BR-61: surcharge for the Express PROCESSING tier (1-2 working days instead of 3-5),
    -- per roll, set by the lab in its price list; NULL = no Express tier. Not a shipping fee.
    CONSTRAINT ck_service_packages_express CHECK (express_surcharge_vnd IS NULL OR express_surcharge_vnd > 0),
    -- Withdrawn instead of deleted when referenced by an order (UC13).
    CONSTRAINT ck_service_packages_status CHECK (status IN ('ON_SALE', 'WITHDRAWN')),
    CONSTRAINT fk_service_packages_lab FOREIGN KEY (film_lab_id)
        REFERENCES film_labs (id),
    CONSTRAINT fk_service_packages_service_type FOREIGN KEY (service_type_id)
        REFERENCES service_types (id),
    CONSTRAINT fk_service_packages_film_process FOREIGN KEY (film_process_id)
        REFERENCES film_processes (id),
    CONSTRAINT fk_service_packages_film_format FOREIGN KEY (film_format_id)
        REFERENCES film_formats (id)
);

-- UC13: package name unique within the same lab, case-insensitive.
-- Leading column film_lab_id also serves "price list of one lab" (SCR-11, SCR-41).
CREATE UNIQUE INDEX uq_service_packages_lab_name
    ON service_packages (film_lab_id, lower(package_name));

-- Scan resolution options of a package (UC13: each level has its own price).
CREATE TABLE service_package_scan_options (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    service_package_id  bigint        NOT NULL,
    resolution_label    varchar(50)   NOT NULL,
    price_vnd           bigint        NOT NULL,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_service_package_scan_options PRIMARY KEY (id),
    CONSTRAINT uq_service_package_scan_options_label UNIQUE (service_package_id, resolution_label),
    CONSTRAINT ck_service_package_scan_options_price CHECK (price_vnd > 0),
    CONSTRAINT fk_service_package_scan_options_package FOREIGN KEY (service_package_id)
        REFERENCES service_packages (id) ON DELETE CASCADE
);
