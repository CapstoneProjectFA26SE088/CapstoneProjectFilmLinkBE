-- Life of one item (consignment_items.status):
--   AWAITING_DROP_OFF -> AWAITING_INSPECTION -> [AWAITING_SELLER_CONFIRMATION] -> NEGOTIATING
--   -> READY_TO_LIST -> LISTED -> SOLD
--   any step can end in AWAITING_COLLECTION -> COLLECTED (seller takes it back), or CANCELLED
--   (appointment missed) or LOST_OR_DAMAGED (UH-48, the lab compensates).

-- =====================================================================================
-- 1. LAB CONSIGNMENT SETTINGS (UC45, BR-54)
-- One row per lab that has ever opened consignment. Kept apart from film_labs so that the
-- cluster 1 table does not change.
-- =====================================================================================

CREATE TABLE consignment_lab_settings (
    film_lab_id                 bigint         NOT NULL,
    is_accepting_consignments   boolean        NOT NULL DEFAULT false,
    consignment_fee_rate        numeric(5,2),
    slot_minutes                smallint       NOT NULL DEFAULT 30,
    appointments_per_slot       smallint       NOT NULL DEFAULT 1,
    created_at                  timestamptz    NOT NULL DEFAULT now(),
    updated_at                  timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_lab_settings PRIMARY KEY (film_lab_id),
    -- BR-54: fee set individually per lab; NULL = system default CONSIGNMENT_FEE_RATE.
    CONSTRAINT ck_consignment_lab_settings_fee CHECK (consignment_fee_rate IS NULL OR consignment_fee_rate BETWEEN 0 AND 100),
    -- [TBC] slot length chosen by the lab, in steps of 15 minutes, 15 min - 4 h.
    CONSTRAINT ck_consignment_lab_settings_slot CHECK (slot_minutes BETWEEN 15 AND 240 AND slot_minutes % 15 = 0),
    CONSTRAINT ck_consignment_lab_settings_capacity CHECK (appointments_per_slot BETWEEN 1 AND 20),
    CONSTRAINT fk_consignment_lab_settings_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id)
);

COMMENT ON TABLE consignment_lab_settings IS 'Slots are generated inside film_lab_opening_hours, slot_minutes long, at most appointments_per_slot bookings each (UC45).';


-- =====================================================================================
-- 2. BOOKING AND ITEM (ERD #31, #32; UC45; BR-49, UH-43)
-- =====================================================================================

CREATE TABLE consignment_bookings (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    booking_code            varchar(20)    NOT NULL,
    seller_account_id       bigint         NOT NULL,
    film_lab_id             bigint         NOT NULL,
    slot_start_at           timestamptz    NOT NULL,
    slot_end_at             timestamptz    NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'BOOKED',
    checked_in_at           timestamptz,
    cancelled_at            timestamptz,
    cancellation_reason     varchar(300),
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_bookings PRIMARY KEY (id),
    CONSTRAINT uq_consignment_bookings_code UNIQUE (booking_code),
    CONSTRAINT ck_consignment_bookings_slot CHECK (slot_end_at > slot_start_at),
    -- BOOKED -> CHECKED_IN (item brought in) | CANCELLED (by seller or lab) | MISSED (not brought
    -- within 24 h, UH-43; 3 MISSED in a row lock booking for 30 days - computed, not stored).
    CONSTRAINT ck_consignment_bookings_status CHECK (status IN ('BOOKED', 'CHECKED_IN', 'CANCELLED', 'MISSED')),
    CONSTRAINT ck_consignment_bookings_checkin CHECK ((status = 'CHECKED_IN') = (checked_in_at IS NOT NULL)),
    CONSTRAINT ck_consignment_bookings_cancel CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CONSTRAINT fk_consignment_bookings_seller FOREIGN KEY (seller_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_consignment_bookings_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id)
);

COMMENT ON COLUMN consignment_bookings.version IS 'Optimistic locking; slot capacity is checked by the service while holding a row lock on consignment_lab_settings.';

-- UC45 free slots of a lab and SCR lab agenda: active bookings of one lab in a time range.
CREATE INDEX ix_consignment_bookings_lab_slot
    ON consignment_bookings (film_lab_id, slot_start_at) WHERE status IN ('BOOKED', 'CHECKED_IN');

-- UC45 "max 5 pending appointments" and UH-43 "3 consecutive misses": history of one seller.
CREATE INDEX ix_consignment_bookings_seller ON consignment_bookings (seller_account_id, slot_start_at DESC);

-- Non-screen #27 (hourly): appointments not honoured 24 h after the slot.
CREATE INDEX ix_consignment_bookings_open_slot ON consignment_bookings (slot_end_at) WHERE status = 'BOOKED';


CREATE TABLE consignment_items (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_booking_id  bigint         NOT NULL,
    item_type               varchar(20)    NOT NULL,
    item_name               varchar(150)   NOT NULL,
    seller_description      varchar(2000)  NOT NULL,
    desired_price_vnd       bigint,
    status                  varchar(30)    NOT NULL DEFAULT 'AWAITING_DROP_OFF',
    closing_reason          varchar(30),
    agreed_price_vnd        bigint,
    price_agreed_at         timestamptz,
    collection_due_at       timestamptz,
    collected_at            timestamptz,
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_items PRIMARY KEY (id),
    CONSTRAINT ck_consignment_items_type CHECK (item_type IN ('CAMERA_BODY', 'LENS', 'FILM')),
    CONSTRAINT ck_consignment_items_name CHECK (char_length(item_name) BETWEEN 2 AND 150),
    CONSTRAINT ck_consignment_items_description CHECK (char_length(seller_description) BETWEEN 20 AND 2000),
    -- UC47: prices are positive VND, at most 500,000,000.
    CONSTRAINT ck_consignment_items_desired_price CHECK (desired_price_vnd IS NULL OR desired_price_vnd BETWEEN 1 AND 500000000),
    CONSTRAINT ck_consignment_items_agreed_price CHECK (agreed_price_vnd IS NULL OR agreed_price_vnd BETWEEN 1 AND 500000000),
    CONSTRAINT ck_consignment_items_status CHECK (status IN (
        'AWAITING_DROP_OFF', 'AWAITING_INSPECTION', 'AWAITING_SELLER_CONFIRMATION', 'NEGOTIATING',
        'READY_TO_LIST', 'LISTED', 'SOLD', 'AWAITING_COLLECTION', 'COLLECTED', 'CANCELLED', 'LOST_OR_DAMAGED')),
    -- Why the item goes back to the seller (or is lost); NULL while the consignment is alive.
    CONSTRAINT ck_consignment_items_closing CHECK (
        (status IN ('AWAITING_COLLECTION', 'COLLECTED', 'CANCELLED', 'LOST_OR_DAMAGED')) = (closing_reason IS NOT NULL)
        AND (closing_reason IS NULL OR closing_reason IN (
            'DECLINED_AT_INSPECTION', 'GRADE_DISPUTED', 'NEGOTIATION_FAILED', 'WITHDRAWN_BY_SELLER',
            'EXPIRED_NO_RESPONSE', 'TAKEN_BACK_AT_EXPIRY', 'REMOVED_BY_MODERATOR', 'BOOKING_MISSED',
            'RETURNED_BY_BUYER', 'LOST_OR_DAMAGED_AT_LAB'))),
    -- BR-52: from READY_TO_LIST on, an agreed price exists.
    CONSTRAINT ck_consignment_items_agreed CHECK (
        (agreed_price_vnd IS NULL) = (price_agreed_at IS NULL)
        AND (status NOT IN ('READY_TO_LIST', 'LISTED', 'SOLD') OR agreed_price_vnd IS NOT NULL)),
    CONSTRAINT ck_consignment_items_collected CHECK ((status = 'COLLECTED') = (collected_at IS NOT NULL)),
    CONSTRAINT fk_consignment_items_booking FOREIGN KEY (consignment_booking_id) REFERENCES consignment_bookings (id)
);

COMMENT ON COLUMN consignment_items.collection_due_at IS 'UH-45: after a failed negotiation the seller collects within 7 days.';

CREATE INDEX ix_consignment_items_booking ON consignment_items (consignment_booking_id);

-- Photos of an item. SELLER: 1-10 taken by the seller (UC45). INSPECTION: 4-20 taken by the lab
-- (UC46, BR-51). The source is always shown (UC48). Counts are enforced by the service.
CREATE TABLE consignment_item_photos (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_item_id     bigint         NOT NULL,
    source                  varchar(20)    NOT NULL,
    blob_key                varchar(500)   NOT NULL,
    display_order           smallint       NOT NULL,
    uploaded_by_account_id  bigint         NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_consignment_item_photos PRIMARY KEY (id),
    CONSTRAINT ck_consignment_item_photos_source CHECK (source IN ('SELLER', 'INSPECTION')),
    CONSTRAINT uq_consignment_item_photos_order UNIQUE (consignment_item_id, source, display_order),
    CONSTRAINT ck_consignment_item_photos_order CHECK (display_order BETWEEN 1 AND 20),
    CONSTRAINT fk_consignment_item_photos_item FOREIGN KEY (consignment_item_id) REFERENCES consignment_items (id),
    CONSTRAINT fk_consignment_item_photos_uploader FOREIGN KEY (uploaded_by_account_id) REFERENCES user_accounts (id)
);


-- =====================================================================================
-- 3. CONDITION REPORT (ERD #33; UC46; BR-47, BR-51)
-- One current report per item; every edit is audited (UC46: an edit after publication means the
-- listing is taken down and the report prepared again).
-- =====================================================================================

CREATE TABLE condition_reports (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    consignment_item_id     bigint         NOT NULL,
    overall_grade           char(1),
    conclusion              varchar(20)    NOT NULL,
    decline_reason          varchar(500),
    corrected_item_name     varchar(150),
    discrepancy_note        varchar(1000),
    seller_confirmed_at     timestamptz,
    film_expiry_date        date,
    inspector_account_id    bigint         NOT NULL,
    inspected_at            timestamptz    NOT NULL DEFAULT now(),
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_condition_reports PRIMARY KEY (id),
    CONSTRAINT uq_condition_reports_item UNIQUE (consignment_item_id),
    -- BR-51: A like new, B good working condition, C cosmetic defects, D needs repair.
    CONSTRAINT ck_condition_reports_grade CHECK (overall_grade IS NULL OR overall_grade IN ('A', 'B', 'C', 'D')),
    CONSTRAINT ck_condition_reports_conclusion CHECK (conclusion IN ('ACCEPTED', 'DECLINED')),
    -- UC46: accepted needs a grade; declined needs a reason of 20-500 characters.
    CONSTRAINT ck_condition_reports_outcome CHECK (
        (conclusion = 'ACCEPTED' AND overall_grade IS NOT NULL AND decline_reason IS NULL)
        OR (conclusion = 'DECLINED' AND decline_reason IS NOT NULL AND char_length(decline_reason) >= 20)),
    -- UC46: when the real item differs from the declaration, the seller must confirm before pricing.
    CONSTRAINT ck_condition_reports_discrepancy CHECK (
        seller_confirmed_at IS NULL OR discrepancy_note IS NOT NULL),
    CONSTRAINT fk_condition_reports_item FOREIGN KEY (consignment_item_id) REFERENCES consignment_items (id),
    CONSTRAINT fk_condition_reports_inspector FOREIGN KEY (inspector_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN condition_reports.inspector_account_id IS 'Recorded automatically from the signed-in account; not editable (UC46).';
COMMENT ON COLUMN condition_reports.film_expiry_date IS 'Film checklist: expiry date (UC46).';

-- Checklist lines. The codes valid for an item depend on its type (camera body, lens, film);
-- that pairing is enforced by the service, the list of codes by the CHECK.
CREATE TABLE condition_report_checks (
    condition_report_id     bigint         NOT NULL,
    check_code              varchar(30)    NOT NULL,
    result                  varchar(20)    NOT NULL,
    note                    varchar(200),
    CONSTRAINT pk_condition_report_checks PRIMARY KEY (condition_report_id, check_code),
    CONSTRAINT ck_condition_report_checks_code CHECK (check_code IN (
        -- camera body
        'SHUTTER', 'LIGHT_METERING', 'MIRROR', 'BATTERY_COMPARTMENT', 'LIGHT_SEALS', 'FRAME_COUNTER',
        -- lens
        'FUNGUS', 'SCRATCHES', 'HAZE', 'APERTURE', 'FOCUS_RING', 'MOUNT',
        -- film
        'EXPIRY_DATE', 'STORAGE_CONDITIONS', 'FACTORY_SEAL')),
    CONSTRAINT ck_condition_report_checks_result CHECK (result IN ('PASS', 'DEFECTIVE', 'NOT_CHECKABLE')),
    CONSTRAINT fk_condition_report_checks_report FOREIGN KEY (condition_report_id)
        REFERENCES condition_reports (id) ON DELETE CASCADE
);
