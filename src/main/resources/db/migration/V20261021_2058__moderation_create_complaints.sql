-- =====================================================================================
-- 7. COMPLAINT (ERD #49; UC51, UC52; BR-15, BR-25, BR-45, BR-47)
-- Money-related disputes, decided by the Admin. Always tied to an order or a consignment sale,
-- where the evidence lives (UC51).
-- =====================================================================================

CREATE TABLE complaints (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    complaint_code          varchar(20)    NOT NULL,
    raised_by_account_id    bigint         NOT NULL,
    service_order_id        bigint,
    consignment_sale_id     bigint,
    complaint_type          varchar(30)    NOT NULL,
    description             varchar(2000)  NOT NULL,
    status                  varchar(25)    NOT NULL DEFAULT 'OPEN',
    information_requested_at timestamptz,
    information_due_at      timestamptz,
    conclusion              varchar(20),
    resolution_reason       varchar(2000),
    refund_amount_vnd       bigint,
    is_commission_waived    boolean        NOT NULL DEFAULT false,
    resolved_by_account_id  bigint,
    resolved_at             timestamptz,
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_complaints PRIMARY KEY (id),
    CONSTRAINT uq_complaints_code UNIQUE (complaint_code),
    CONSTRAINT ck_complaints_owner CHECK (num_nonnulls(service_order_id, consignment_sale_id) = 1),
    -- UC51 types; ITEM_CONDITION / ITEM_LOST_OR_DAMAGED are the consignment disputes (BR-47, UH-48);
    -- COMMISSION_STATEMENT = a lab disputes one order of its debt statement (UC33).
    CONSTRAINT ck_complaints_type CHECK (complaint_type IN (
        'REFUND_REQUEST', 'DAMAGED_FILM', 'PAYMENT_DISPUTE', 'ROLL_COUNT_DISPUTE', 'SCAN_QUALITY',
        'LOST_IN_TRANSIT', 'ITEM_CONDITION', 'ITEM_LOST_OR_DAMAGED', 'COMMISSION_STATEMENT', 'OTHER')),
    CONSTRAINT ck_complaints_description CHECK (char_length(description) BETWEEN 20 AND 2000),
    -- AWAITING_INFORMATION: a party has 7 days to add evidence (UC52).
    CONSTRAINT ck_complaints_status CHECK (status IN ('OPEN', 'AWAITING_INFORMATION', 'RESOLVED')),
    CONSTRAINT ck_complaints_info CHECK (
        (information_requested_at IS NULL) = (information_due_at IS NULL)
        AND (status <> 'AWAITING_INFORMATION' OR information_due_at IS NOT NULL)),
    -- UC52: conclusion and a 20-2000 character reason are mandatory when resolved.
    CONSTRAINT ck_complaints_resolution CHECK (
        (status = 'RESOLVED') = (conclusion IS NOT NULL)
        AND (status = 'RESOLVED') = (resolved_at IS NOT NULL)
        AND (conclusion IS NULL OR (conclusion IN ('FULLY_UPHELD', 'PARTIALLY_UPHELD', 'DISMISSED')
             AND resolution_reason IS NOT NULL AND char_length(resolution_reason) >= 20))),
    -- UC52: a refund amount is mandatory when upheld (<= amount collected: checked by the service).
    CONSTRAINT ck_complaints_refund CHECK (
        (conclusion IN ('FULLY_UPHELD', 'PARTIALLY_UPHELD')) = (refund_amount_vnd IS NOT NULL)
        AND (refund_amount_vnd IS NULL OR refund_amount_vnd >= 0)),
    CONSTRAINT fk_complaints_raiser FOREIGN KEY (raised_by_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_complaints_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_complaints_sale FOREIGN KEY (consignment_sale_id) REFERENCES consignment_sales (id),
    CONSTRAINT fk_complaints_resolver FOREIGN KEY (resolved_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON COLUMN complaints.is_commission_waived IS 'UC52: fault of the lab -> Commission of the order reduced to 0 (an ADJUSTMENT row if the period is already closed).';

-- UC51: a second open complaint of the same type on the same order is merged, not created.
CREATE UNIQUE INDEX uq_complaints_open_order
    ON complaints (service_order_id, complaint_type) WHERE status <> 'RESOLVED' AND service_order_id IS NOT NULL;
CREATE UNIQUE INDEX uq_complaints_open_sale
    ON complaints (consignment_sale_id, complaint_type) WHERE status <> 'RESOLVED' AND consignment_sale_id IS NOT NULL;

-- SCR Admin queue (UC52), oldest first; BR-45 "open complaint on this order?" uses the indexes above.
CREATE INDEX ix_complaints_queue ON complaints (status, created_at) WHERE status <> 'RESOLVED';

ALTER TABLE commissions ADD CONSTRAINT fk_commissions_complaint
    FOREIGN KEY (complaint_id) REFERENCES complaints (id);

-- UC51: at most 10 evidence files, <= 10 MB each. Append-only (evidence).
CREATE TABLE complaint_evidence_files (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    complaint_id            bigint         NOT NULL,
    uploaded_by_account_id  bigint         NOT NULL,
    file_name               varchar(255)   NOT NULL,
    blob_key                varchar(500)   NOT NULL,
    content_type            varchar(100)   NOT NULL,
    size_bytes              bigint         NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_complaint_evidence_files PRIMARY KEY (id),
    CONSTRAINT ck_complaint_evidence_files_size CHECK (size_bytes BETWEEN 1 AND 10485760),
    CONSTRAINT fk_complaint_evidence_files_complaint FOREIGN KEY (complaint_id) REFERENCES complaints (id),
    CONSTRAINT fk_complaint_evidence_files_uploader FOREIGN KEY (uploaded_by_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_complaint_evidence_files_complaint ON complaint_evidence_files (complaint_id);

CREATE TRIGGER complaint_evidence_files_append_only
    BEFORE UPDATE OR DELETE ON complaint_evidence_files
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();
