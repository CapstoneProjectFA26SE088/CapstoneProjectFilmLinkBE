-- =====================================================================================
-- 1. COMMISSION RATE RULES (BR-10, UC54)
-- Effective rate of a Service Order = rule of its Service Package, else rule of its Film Lab,
-- else system_parameters.DEFAULT_COMMISSION_RATE. The rate actually used is copied into
-- commissions.rate_percent, so changing a rule never changes an existing Commission.
-- =====================================================================================

CREATE TABLE commission_rate_rules (
    id                     bigint         GENERATED BY DEFAULT AS IDENTITY,
    film_lab_id            bigint,
    service_package_id     bigint,
    rate_percent           numeric(5,2)   NOT NULL,
    note                   varchar(300),
    created_by_account_id  bigint         NOT NULL,
    created_at             timestamptz    NOT NULL DEFAULT now(),
    updated_at             timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_commission_rate_rules PRIMARY KEY (id),
    -- A rule targets exactly one thing: one lab, or one package.
    CONSTRAINT ck_commission_rate_rules_target CHECK (num_nonnulls(film_lab_id, service_package_id) = 1),
    -- UC54: 0-30%. 0 is allowed (the Admin is warned, not blocked).
    CONSTRAINT ck_commission_rate_rules_rate CHECK (rate_percent BETWEEN 0 AND 30),
    CONSTRAINT fk_commission_rate_rules_lab FOREIGN KEY (film_lab_id) REFERENCES film_labs (id),
    CONSTRAINT fk_commission_rate_rules_package FOREIGN KEY (service_package_id) REFERENCES service_packages (id),
    CONSTRAINT fk_commission_rate_rules_creator FOREIGN KEY (created_by_account_id) REFERENCES user_accounts (id)
);

-- At most one rule per lab and one per package (also the lookup path of the rate resolver).
CREATE UNIQUE INDEX uq_commission_rate_rules_lab
    ON commission_rate_rules (film_lab_id) WHERE film_lab_id IS NOT NULL;
CREATE UNIQUE INDEX uq_commission_rate_rules_package
    ON commission_rate_rules (service_package_id) WHERE service_package_id IS NOT NULL;


-- =====================================================================================
-- 2. PAYMENT (ERD #26; UC30, UC31, UC33, UC62; BR-09, BR-14, BR-18, BR-19, BR-55)
-- One row = one money movement between the platform world and a person:
--   IN  : ORDER_PAYMENT, ORDER_TOP_UP, SALE_PAYMENT, DEBT_PAYMENT
--   OUT : ORDER_REFUND, SALE_REFUND
-- Money that does not pass through the platform (PAY_AT_LAB, COD) is still recorded here,
-- because it closes the order and feeds the Commission Debt (UC31, UC32).
-- =====================================================================================

CREATE TABLE payments (
    id                         bigint         GENERATED BY DEFAULT AS IDENTITY,
    transaction_code           varchar(30)    NOT NULL,
    purpose                    varchar(20)    NOT NULL,
    direction                  varchar(3)     NOT NULL,
    method                     varchar(20)    NOT NULL,
    status                     varchar(20)    NOT NULL DEFAULT 'PENDING',
    amount_vnd                 bigint         NOT NULL,
    -- Owner: exactly one of the three (consistent with purpose, see CHECK below).
    service_order_id           bigint,
    consignment_sale_id        bigint,
    commission_debt_id         bigint,
    -- Person who pays (IN) or who receives the refund (OUT).
    counterparty_account_id    bigint         NOT NULL,
    -- Refund of which payment (UH-41: refunded through the method used for paying).
    refunded_payment_id        bigint,
    -- VNPay (UC30): link valid 15 minutes, IPN result.
    payment_url_expires_at     timestamptz,
    gateway_transaction_no     varchar(50),
    gateway_response_code      varchar(10),
    gateway_bank_code          varchar(20),
    -- COD collected by the Delivery Partner (UC31): idempotent per waybill.
    shipment_id                bigint,
    -- PAY_AT_LAB / BANK_TRANSFER / manual refund: who recorded it, with which evidence.
    recorded_by_account_id     bigint,
    receipt_blob_key           varchar(500),
    -- UC31: the Photographer confirms a Pay-at-Lab record within 7 days.
    confirmation_status        varchar(25)    NOT NULL DEFAULT 'NOT_REQUIRED',
    confirmation_due_at        timestamptz,
    confirmation_reminder_count smallint      NOT NULL DEFAULT 0,
    confirmed_at               timestamptz,
    succeeded_at               timestamptz,
    failure_reason             varchar(500),
    version                    integer        NOT NULL DEFAULT 0,
    created_at                 timestamptz    NOT NULL DEFAULT now(),
    updated_at                 timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT pk_payments PRIMARY KEY (id),
    -- UC30: unique internal code used for reconciliation (sent to VNPay as vnp_TxnRef).
    CONSTRAINT uq_payments_transaction_code UNIQUE (transaction_code),
    CONSTRAINT ck_payments_purpose CHECK (purpose IN
        ('ORDER_PAYMENT', 'ORDER_TOP_UP', 'ORDER_REFUND', 'SALE_PAYMENT', 'SALE_REFUND', 'DEBT_PAYMENT')),
    CONSTRAINT ck_payments_direction CHECK (
        direction = CASE WHEN purpose IN ('ORDER_REFUND', 'SALE_REFUND') THEN 'OUT' ELSE 'IN' END),
    -- VNPAY = through the gateway; PAY_AT_LAB, COD = outside the platform (BR-09);
    -- BANK_TRANSFER = manual transfer with a receipt (UC33 debt payment, UH-24 manual refund).
    CONSTRAINT ck_payments_method CHECK (method IN ('VNPAY', 'PAY_AT_LAB', 'COD', 'BANK_TRANSFER')),
    CONSTRAINT ck_payments_status CHECK (status IN
        ('PENDING', 'SUCCEEDED', 'FAILED', 'EXPIRED', 'CANCELLED', 'AWAITING_MANUAL')),
    CONSTRAINT ck_payments_amount CHECK (amount_vnd > 0),
    CONSTRAINT ck_payments_owner CHECK (
        num_nonnulls(service_order_id, consignment_sale_id, commission_debt_id) = 1
        AND (purpose NOT IN ('ORDER_PAYMENT', 'ORDER_TOP_UP', 'ORDER_REFUND') OR service_order_id IS NOT NULL)
        AND (purpose NOT IN ('SALE_PAYMENT', 'SALE_REFUND') OR consignment_sale_id IS NOT NULL)
        AND (purpose <> 'DEBT_PAYMENT' OR commission_debt_id IS NOT NULL)),
    -- A refund always points at the payment it gives back; nothing else does.
    CONSTRAINT ck_payments_refund_link CHECK ((direction = 'OUT') = (refunded_payment_id IS NOT NULL)),
    -- COD exists only for Service Orders (BR-09); a consignment buyer pays online or at the lab (BR-14).
    CONSTRAINT ck_payments_cod CHECK (method <> 'COD' OR purpose IN ('ORDER_PAYMENT', 'ORDER_TOP_UP')),
    CONSTRAINT ck_payments_cod_shipment CHECK ((method = 'COD') = (shipment_id IS NOT NULL)),
    -- UC33: a bank transfer needs the image of the payment order.
    CONSTRAINT ck_payments_receipt CHECK (
        method <> 'BANK_TRANSFER' OR status <> 'SUCCEEDED' OR receipt_blob_key IS NOT NULL),
    -- Money not passing through the gateway is recorded by a person (lab or Admin).
    CONSTRAINT ck_payments_recorder CHECK (method NOT IN ('PAY_AT_LAB', 'BANK_TRANSFER') OR recorded_by_account_id IS NOT NULL),
    CONSTRAINT ck_payments_succeeded CHECK ((status = 'SUCCEEDED') = (succeeded_at IS NOT NULL)),
    CONSTRAINT ck_payments_vnpay_url CHECK (method <> 'VNPAY' OR direction = 'OUT' OR payment_url_expires_at IS NOT NULL),
    CONSTRAINT ck_payments_confirmation CHECK (
        confirmation_status IN ('NOT_REQUIRED', 'AWAITING_CONFIRMATION', 'CONFIRMED', 'DISPUTED')
        AND (confirmation_status = 'NOT_REQUIRED' OR method = 'PAY_AT_LAB')
        AND ((confirmation_status = 'NOT_REQUIRED') = (confirmation_due_at IS NULL))
        AND ((confirmation_status = 'CONFIRMED') = (confirmed_at IS NOT NULL))),
    -- UC31: three reminders, then the Admin decides.
    CONSTRAINT ck_payments_reminders CHECK (confirmation_reminder_count BETWEEN 0 AND 3),
    CONSTRAINT fk_payments_order FOREIGN KEY (service_order_id) REFERENCES service_orders (id),
    CONSTRAINT fk_payments_counterparty FOREIGN KEY (counterparty_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_payments_refunded FOREIGN KEY (refunded_payment_id) REFERENCES payments (id),
    CONSTRAINT fk_payments_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id),
    CONSTRAINT fk_payments_recorder FOREIGN KEY (recorded_by_account_id) REFERENCES user_accounts (id)
);

COMMENT ON TABLE  payments IS 'Every money movement of an order, a consignment sale or a Commission Debt. Card data is never stored (NFR-SEC-03).';
COMMENT ON COLUMN payments.status IS 'AWAITING_MANUAL: automatic refund failed, waiting for the Admin bank transfer on SCR-58 (UH-24).';
COMMENT ON COLUMN payments.version IS 'Optimistic locking: the IPN callback and the reconciliation job may update the same row at once (UH-19).';
COMMENT ON COLUMN payments.confirmation_status IS 'UC31: DISPUTED = the Photographer denies the Pay-at-Lab record -> Complaint (UH-22).';

-- Order detail, sale detail, debt detail: all payments of one owner.
CREATE INDEX ix_payments_order ON payments (service_order_id) WHERE service_order_id IS NOT NULL;
CREATE INDEX ix_payments_sale ON payments (consignment_sale_id) WHERE consignment_sale_id IS NOT NULL;
CREATE INDEX ix_payments_debt ON payments (commission_debt_id) WHERE commission_debt_id IS NOT NULL;

-- UC31: a duplicate COD webhook must not be recorded twice (idempotent by waybill).
CREATE UNIQUE INDEX uq_payments_cod_shipment ON payments (shipment_id) WHERE method = 'COD';

-- Non-screen #4 (every 15 min): VNPay payments without a final IPN.
--   WHERE method = 'VNPAY' AND status = 'PENDING' AND created_at < now() - interval '15 minutes'
CREATE INDEX ix_payments_vnpay_pending ON payments (created_at) WHERE method = 'VNPAY' AND status = 'PENDING';

-- UC31 reminders: Pay-at-Lab records not yet confirmed by the Photographer.
CREATE INDEX ix_payments_awaiting_confirmation
    ON payments (confirmation_due_at) WHERE confirmation_status = 'AWAITING_CONFIRMATION';

-- SCR-58 manual queue (UH-24).
CREATE INDEX ix_payments_awaiting_manual ON payments (created_at) WHERE status = 'AWAITING_MANUAL';


-- Payment gateway callbacks (non-screen #18): raw evidence of every IPN / return / query.
-- Append-only. A callback repeated by VNPay hits the unique key and is ignored (UH-20).
CREATE TABLE payment_gateway_events (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    provider                varchar(20)    NOT NULL DEFAULT 'VNPAY',
    event_type              varchar(20)    NOT NULL,
    transaction_code        varchar(30)    NOT NULL,
    payment_id              bigint,
    gateway_transaction_no  varchar(50),
    response_code           varchar(10),
    amount_vnd              bigint,
    is_signature_valid      boolean        NOT NULL,
    raw_payload             jsonb          NOT NULL,
    received_at             timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_payment_gateway_events PRIMARY KEY (id),
    -- IPN = server callback, RETURN = browser redirect, QUERY = reconciliation job (UH-19).
    CONSTRAINT ck_payment_gateway_events_type CHECK (event_type IN ('IPN', 'RETURN', 'QUERY')),
    CONSTRAINT ck_payment_gateway_events_amount CHECK (amount_vnd IS NULL OR amount_vnd >= 0),
    CONSTRAINT uq_payment_gateway_events_dedup UNIQUE NULLS NOT DISTINCT
        (provider, event_type, transaction_code, gateway_transaction_no, response_code),
    -- NULL when the transaction code is unknown (kept as evidence of a forged/stray call).
    CONSTRAINT fk_payment_gateway_events_payment FOREIGN KEY (payment_id) REFERENCES payments (id)
);

CREATE TRIGGER payment_gateway_events_append_only
    BEFORE UPDATE OR DELETE ON payment_gateway_events
    FOR EACH ROW EXECUTE FUNCTION trg_append_only();
