-- =====================================================================================
-- 2. MASTER DATA (BR-16, UC53)
-- Three separate tables, not one generic "master_data(type, code)" table: a foreign key
-- from service_packages.film_process_id can then only point at a Film Process, never at
-- a Film Format by mistake.
-- =====================================================================================

CREATE TABLE film_processes (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    code          varchar(20)   NOT NULL,
    display_name  varchar(100)  NOT NULL,
    description   varchar(500),
    status        varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_processes PRIMARY KEY (id),
    CONSTRAINT uq_film_processes_code UNIQUE (code),
    CONSTRAINT ck_film_processes_display_name CHECK (char_length(display_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_film_processes_status CHECK (status IN ('ACTIVE', 'DISCONTINUED'))
);

CREATE TABLE film_formats (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    code          varchar(20)   NOT NULL,
    display_name  varchar(100)  NOT NULL,
    description   varchar(500),
    status        varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_formats PRIMARY KEY (id),
    CONSTRAINT uq_film_formats_code UNIQUE (code),
    CONSTRAINT ck_film_formats_display_name CHECK (char_length(display_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_film_formats_status CHECK (status IN ('ACTIVE', 'DISCONTINUED'))
);

CREATE TABLE service_types (
    id            bigint        GENERATED BY DEFAULT AS IDENTITY,
    code          varchar(20)   NOT NULL,
    display_name  varchar(100)  NOT NULL,
    description   varchar(500),
    status        varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_service_types PRIMARY KEY (id),
    CONSTRAINT uq_service_types_code UNIQUE (code),
    CONSTRAINT ck_service_types_display_name CHECK (char_length(display_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_service_types_status CHECK (status IN ('ACTIVE', 'DISCONTINUED'))
);

-- Film Stock catalogue (decision 14/10/2026). Admin-managed like the other master data.
-- A roll references a stock from this list, or carries a free-text name when the stock is
-- not listed (UC20); the Admin can later add the stock and re-link the rolls.
CREATE TABLE film_stocks (
    id                       bigint        GENERATED BY DEFAULT AS IDENTITY,
    stock_name               varchar(100)  NOT NULL,
    manufacturer             varchar(100)  NOT NULL,
    iso                      smallint      NOT NULL,
    default_film_process_id  bigint        NOT NULL,
    status                   varchar(20)   NOT NULL DEFAULT 'ACTIVE',
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_film_stocks PRIMARY KEY (id),
    CONSTRAINT ck_film_stocks_iso CHECK (iso BETWEEN 1 AND 6400),
    CONSTRAINT ck_film_stocks_status CHECK (status IN ('ACTIVE', 'DISCONTINUED')),
    CONSTRAINT fk_film_stocks_process FOREIGN KEY (default_film_process_id)
        REFERENCES film_processes (id)
);

-- One catalogue entry per name, case-insensitive ("Portra 400" = "portra 400").
CREATE UNIQUE INDEX uq_film_stocks_name ON film_stocks (lower(manufacturer), lower(stock_name));

COMMENT ON COLUMN film_stocks.default_film_process_id IS 'Usual process (e.g. Ilford XP2 is B&W but developed in C-41; CineStill 800T is C-41).';

COMMENT ON COLUMN film_processes.code IS 'Unique, not editable after creation (UC53) - enforced in the service layer.';

