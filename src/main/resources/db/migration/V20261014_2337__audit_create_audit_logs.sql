-- =====================================================================================
-- 5. AUDIT LOG (ERD #53) - designed now because every cluster writes to it
-- BR-32, CR-16, NFR-SEC-08, NFR-DAT-03: actor, action, target, timestamp, outcome;
-- read-only for the application; retention >= 12 months.
-- =====================================================================================

CREATE TABLE audit_logs (
    id                 bigint        GENERATED BY DEFAULT AS IDENTITY,
    occurred_at        timestamptz   NOT NULL DEFAULT now(),
    actor_account_id   bigint,
    actor_role         varchar(30),
    action             varchar(100)  NOT NULL,
    target_type        varchar(50)   NOT NULL,
    target_id          bigint,
    outcome            varchar(20)   NOT NULL,
    reason             varchar(500),
    before_data        jsonb,
    after_data         jsonb,
    client_ip          inet,
    CONSTRAINT pk_audit_logs PRIMARY KEY (id),
    CONSTRAINT ck_audit_logs_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE')),
    CONSTRAINT fk_audit_logs_actor FOREIGN KEY (actor_account_id)
        REFERENCES user_accounts (id)
);

COMMENT ON TABLE  audit_logs IS 'Append-only. No created_at/updated_at: the entity does not extend BaseEntity.';
COMMENT ON COLUMN audit_logs.actor_account_id IS 'NULL when the actor is System (Scheduler).';
COMMENT ON COLUMN audit_logs.actor_role IS 'Role at the time of the action (a role can change later, e.g. Expert upgrade).';

-- Admin views the history of one record, newest first (complaint handling UC52,
-- schedule-change trail CR-20, parameter history UC54):
--   SELECT ... FROM audit_logs WHERE target_type = :t AND target_id = :id ORDER BY occurred_at DESC;
CREATE INDEX ix_audit_logs_target
    ON audit_logs (target_type, target_id, occurred_at DESC);

-- Retention job and time-range browsing. Rows arrive in time order, so a BRIN index
-- (a few kB) is enough instead of a B-tree that would grow with every insert.
CREATE INDEX ix_audit_logs_occurred_brin
    ON audit_logs USING brin (occurred_at);

-- Read-only: no UPDATE ever; DELETE only for rows older than the 12-month retention (BR-32).
CREATE FUNCTION trg_audit_logs_read_only() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'audit_logs is append-only';
    END IF;
    IF TG_OP = 'DELETE' AND OLD.occurred_at > now() - interval '12 months' THEN
        RAISE EXCEPTION 'audit_logs rows younger than 12 months cannot be deleted (BR-32)';
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_logs_read_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION trg_audit_logs_read_only();
