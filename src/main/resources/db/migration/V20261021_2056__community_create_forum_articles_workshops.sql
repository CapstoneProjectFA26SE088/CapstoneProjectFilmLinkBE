-- =====================================================================================
-- 3. FORUM (ERD #43, #44; UC41 - Tier Should). The Expert Badge of an answer is derived from
--    the author's current role, not stored.
-- =====================================================================================

CREATE TABLE forum_threads (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    author_account_id       bigint         NOT NULL,
    title                   varchar(200)   NOT NULL,
    content                 varchar(5000)  NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'VISIBLE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_forum_threads PRIMARY KEY (id),
    -- [TBC] lengths not specified by UC41.
    CONSTRAINT ck_forum_threads_title CHECK (char_length(title) BETWEEN 10 AND 200),
    CONSTRAINT ck_forum_threads_content CHECK (char_length(content) BETWEEN 1 AND 5000),
    CONSTRAINT ck_forum_threads_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED')),
    CONSTRAINT fk_forum_threads_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_forum_threads_list ON forum_threads (created_at DESC) WHERE status = 'VISIBLE';

CREATE TABLE forum_answers (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    forum_thread_id         bigint         NOT NULL,
    author_account_id       bigint         NOT NULL,
    content                 varchar(5000)  NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'VISIBLE',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_forum_answers PRIMARY KEY (id),
    CONSTRAINT ck_forum_answers_content CHECK (char_length(content) BETWEEN 1 AND 5000),
    CONSTRAINT ck_forum_answers_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED')),
    CONSTRAINT fk_forum_answers_thread FOREIGN KEY (forum_thread_id) REFERENCES forum_threads (id),
    CONSTRAINT fk_forum_answers_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_forum_answers_thread ON forum_answers (forum_thread_id, created_at);


-- =====================================================================================
-- 4. EXPERT ARTICLE AND KNOWLEDGE BASE (ERD #45, #46; UC42 - UC44; BR-12, BR-29;
--    non-screen #10, #11)
-- An article is public as soon as it is published (BR-12) but enters the Knowledge Base only
-- after a Moderator approves it. Two independent statuses.
-- =====================================================================================

CREATE TABLE expert_articles (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    author_account_id       bigint         NOT NULL,
    title                   varchar(200)   NOT NULL,
    category                varchar(20)    NOT NULL,
    content                 text           NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'PUBLISHED',
    kb_status               varchar(20)    NOT NULL DEFAULT 'NOT_SUBMITTED',
    kb_submitted_at         timestamptz,
    kb_reviewed_by_account_id bigint,
    kb_reviewed_at          timestamptz,
    kb_rejection_reason     varchar(500),
    version                 integer        NOT NULL DEFAULT 0,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_expert_articles PRIMARY KEY (id),
    -- [TBC] lengths not specified by UC42.
    CONSTRAINT ck_expert_articles_title CHECK (char_length(title) BETWEEN 10 AND 200),
    CONSTRAINT ck_expert_articles_content CHECK (char_length(content) >= 100),
    -- UC42: tutorials and reviews of film, cameras and lenses.
    CONSTRAINT ck_expert_articles_category CHECK (category IN ('TUTORIAL', 'FILM_REVIEW', 'CAMERA_REVIEW', 'LENS_REVIEW')),
    CONSTRAINT ck_expert_articles_status CHECK (status IN ('PUBLISHED', 'HIDDEN', 'REMOVED')),
    -- WITHDRAWN = removed from the Knowledge Base after approval (chunks deleted, non-screen #11).
    CONSTRAINT ck_expert_articles_kb_status CHECK (kb_status IN ('NOT_SUBMITTED', 'PENDING_REVIEW', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_expert_articles_kb_submitted CHECK ((kb_status = 'NOT_SUBMITTED') = (kb_submitted_at IS NULL)),
    CONSTRAINT ck_expert_articles_kb_review CHECK (
        (kb_status IN ('APPROVED', 'REJECTED', 'WITHDRAWN')) = (kb_reviewed_at IS NOT NULL)
        AND (kb_status = 'REJECTED') = (kb_rejection_reason IS NOT NULL)),
    CONSTRAINT fk_expert_articles_author FOREIGN KEY (author_account_id) REFERENCES user_accounts (id),
    CONSTRAINT fk_expert_articles_reviewer FOREIGN KEY (kb_reviewed_by_account_id) REFERENCES user_accounts (id)
);

CREATE INDEX ix_expert_articles_list ON expert_articles (created_at DESC) WHERE status = 'PUBLISHED';
-- SCR-51 Moderator queue (UC44).
CREATE INDEX ix_expert_articles_kb_pending ON expert_articles (kb_submitted_at) WHERE kb_status = 'PENDING_REVIEW';

