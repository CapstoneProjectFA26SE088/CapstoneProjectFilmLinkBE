-- =====================================================================================
-- 5. WORKSHOP / PHOTOWALK (ERD #47; UC58, UC59 - Simulated UI; BR-35, BR-48)
-- Information and registrations only: no fee, no check-in (BR-35).
-- =====================================================================================

CREATE TABLE workshop_events (
    id                      bigint         GENERATED BY DEFAULT AS IDENTITY,
    organiser_account_id    bigint         NOT NULL,
    event_type              varchar(20)    NOT NULL,
    title                   varchar(200)   NOT NULL,
    description             varchar(5000),
    location                varchar(255)   NOT NULL,
    starts_at               timestamptz    NOT NULL,
    ends_at                 timestamptz    NOT NULL,
    max_places              smallint       NOT NULL,
    status                  varchar(20)    NOT NULL DEFAULT 'OPEN',
    created_at              timestamptz    NOT NULL DEFAULT now(),
    updated_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_workshop_events PRIMARY KEY (id),
    CONSTRAINT ck_workshop_events_type CHECK (event_type IN ('WORKSHOP', 'PHOTOWALK')),
    CONSTRAINT ck_workshop_events_title CHECK (char_length(title) BETWEEN 5 AND 200),
    CONSTRAINT ck_workshop_events_time CHECK (ends_at > starts_at),
    -- BR-48: time, place and maximum number of places are mandatory.
    CONSTRAINT ck_workshop_events_places CHECK (max_places BETWEEN 1 AND 1000),
    -- FULL is set automatically when the places are filled (BR-48).
    CONSTRAINT ck_workshop_events_status CHECK (status IN ('OPEN', 'FULL', 'CANCELLED', 'FINISHED')),
    CONSTRAINT fk_workshop_events_organiser FOREIGN KEY (organiser_account_id) REFERENCES user_accounts (id)
);

-- "registers for" is a many-to-many relationship on the ERD.
CREATE TABLE workshop_event_registrations (
    workshop_event_id       bigint         NOT NULL,
    user_account_id         bigint         NOT NULL,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT pk_workshop_event_registrations PRIMARY KEY (workshop_event_id, user_account_id),
    CONSTRAINT fk_wer_event FOREIGN KEY (workshop_event_id) REFERENCES workshop_events (id) ON DELETE CASCADE,
    CONSTRAINT fk_wer_user FOREIGN KEY (user_account_id) REFERENCES user_accounts (id)
);
